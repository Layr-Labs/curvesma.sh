"""Frobenius-class mixed rho on GT for the bls12-381 fixed-argument pairing tracks, with cscore.exact.

Work is in target-group-operation units: one dense Fp12 multiplication costs 1, and other
scalar AArch64 instructions cost (instructions / C) with C = 20,000 (COST_MODEL.md). The walk
is specified in work-gt/SPEC-gt-walk.md. The procedure is cut off by a hard total-work counter
W_MAX that covers every operation (walk steps, escapes, distinguished points, verification,
solve and output); the score is log2(W_MAX). Per-step costs and the operation mix come from the
production kernel at the production square count S = 458 (measurement/ in the package). The
cycle rate and every failure term are derived in derive_failure_terms.
"""
import json
import math
from fractions import Fraction

from cscore import exact

R = 0x73eda753299d7d483339d80809a1d80553bda402fffe5bfeffffffff00000001
N = (R - 1) // 12
C = 20000
ADDER_BITS = 10
R_A = 1 << ADDER_BITS
DP_BITS = 60
WALKS = 1 << 20
TARGET = Fraction(41, 100)     # claimed success probability
EXP_UNITS = 381                # one exponentiation by a 255-bit scalar: ~255 squarings + ~127 multiplications, all charged 1
FROBENIUS_UNITS = Fraction(7421, C)  # blst_fp12_frobenius_map, measured (research-arith.md)
DP_INSTRUCTIONS = 2 ** 20      # per distinguished point: record, sort and lookup
SOLVE_INSTRUCTIONS = 2 ** 29   # final scalar multiplication, verification pairing, input checks
CAP_C = 64                     # trail cap in units of 2^DP_BITS: a walk runs at most 64 * 2^60 steps without a DP
CAP = CAP_C * 2 ** DP_BITS     # 2^66 main steps
WINDOW = 127                   # main steps a detected cycle can run before its anchor check fires (2 * 64 - 1)
DP_BYTES = 80                  # 16-byte key fingerprint and two 32-byte canonical exponents
DETECTOR_BYTES = 2 * 48 + 2 + 16  # per walk: previous and anchor keys (48 bytes each), two flags, trail age (128-bit)
ELEMENT_BYTES = 576            # one Fp12 element in blst (12 x 48 bytes)
EXPONENT_BYTES = 32
FINGERPRINT_BITS = 128         # key bits 70..197 of the Montgomery integer: they vary (bits 10..69 are zero by the DP test)

# Uninstrumented runs of the production kernel, S = 458, seeds 1 and 2, 2^20 rounds of 64 walks
# each (measurement/native_run.sh, evidence/native-counts.json).
MEASURED_S = 458
NATIVE_STEPS = 2 * 67108864
NATIVE_ADDS = 37092453 + 37096088      # group operations that are adder multiplications
NATIVE_SQRS = 30022369 + 30018923      # squarings, including escapes
NATIVE_CYCLE2 = 2979 + 3071            # detected 2-cycles
NATIVE_CYCLE_LONG = 1                  # detected longer cycles

# Callgrind interval 256 -> 512 rounds at S = 458 with distinguished-point density zero, seeds 1 and 2
# (measurement/RESULT.json). Distinguished-point work is charged separately (DP_INSTRUCTIONS).
C2 = Fraction(1450, 10000)     # other work per main step: 0.14485 (max of two seeds) with a 0.1% margin, rounded up
KAPPA = Fraction(4902, 10000)  # blst_fp12_cyclotomic_sqr: 9804 instructions, 0.4902


def v_rate(S):
    """Collision rate for S square slots out of R_A: 1 - s^2 - (R_A - S) / R_A^2 (the R_A - S additive
    adders are each selected with probability 1/R_A; the square branch with probability s)."""
    s = Fraction(S, R_A)
    return 1 - s * s - Fraction(R_A - S, R_A * R_A)


def formal_rate(ell, s):
    """Probability per step that a window of ell consecutive steps is a formal cancellation: pairs of
    adder steps (h, k), (h, k + 6), each pair costing one additive first step (probability 1 - s) and one
    specific second step (probability 1 / (12 R_A)). The group is abelian and lambda^6 = -1, so these
    cancel exactly. Rate = (ell - 1)!! ((1 - s) / (12 R_A))^(ell / 2) for even ell, computed in logs.
    For ell = 2 this is (1 - s) / (12 R_A) = 4.4982e-5 per step; the measured 2-cycle rate is 4.5076e-5."""
    if ell % 2:
        return 0.0
    x = (1 - s) / (12 * R_A)
    half = ell // 2
    log_dfact = math.lgamma(ell + 1) - half * math.log(2) - math.lgamma(half + 1)
    return math.exp(log_dfact + half * math.log(x))


def derive_failure_terms(total_steps, s):
    """Failure terms of the success bound. Each term is a probability over the whole run.

    trap: an undetected cycle (length > 64) traps a walk until its trail cap restarts it. Per step:
      (a) formal cancellations of length 66 .. infinity: sum of formal_rate over even ell >= 66;
      (b) non-formal closure of a length-ell cycle: the affine exponent relation (lambda^j - 2^q) e =
          (adder terms) must hold for the secret y; probability 1/r per candidate (heuristic H5), with
          12 candidates (the class power j) per length, and lengths up to CAP: 12 CAP / r in total.
      Union bound over all steps: delta_trap = total_steps * (a + b). Heuristic H6: 2^q is not a
      12th root of unity for any q <= CAP (checked for 2^(12k) != 1 mod r, k <= 200000).
    cap: a collision whose downstream DP lies beyond its trail's cap is lost. Trail age and distance to
      the next DP are geometric with mean 2^DP_BITS, so the loss probability per collision is at most
      2 (1 + c) e^(-c) with c = CAP_C (two trails per collision). It enters the success as a factor f.
    waste: the detected-cycle waste is charged in the budget (not a failure). Its concentration failure
      is bounded by a Chernoff bound for a 1% relative excess over the mean event count.
    """
    tail = sum(formal_rate(ell, s) for ell in range(66, 2000, 2))
    nonformal = 12 * CAP / R
    p_trap = tail + nonformal
    delta_trap = float(total_steps) * p_trap
    mu = float(total_steps) * (NATIVE_CYCLE2 + NATIVE_CYCLE_LONG) / NATIVE_STEPS
    delta_waste = math.exp(-(0.01 ** 2) * mu / 3)
    return {
        "formal_tail_per_step": tail,
        "nonformal_candidates_per_step": nonformal,
        "trap_per_step": p_trap,
        "delta_trap": delta_trap,
        "delta_waste": delta_waste,
        "cap_loss": cap_loss(CAP_C),
        "delta": delta_trap + delta_waste,
    }


def cap_loss(c):
    """Fraction of collisions lost to the trail cap: 2 (1 + c) e^(-c)."""
    return 2 * (1 + c) * math.exp(-c)


def waste_bound(s):
    """Fraction of main steps lost to detected cycles, charged: WINDOW main steps per detection, with
    the one-sided 95% upper bound on the measured rate (normal approximation to the Poisson), and at
    least the formal-model rate of all cycles up to length 64."""
    k = NATIVE_CYCLE2 + NATIVE_CYCLE_LONG
    upper = (k + 1 + 1.6449 * math.sqrt(k + 1)) / NATIVE_STEPS
    model = sum(formal_rate(ell, s) for ell in range(2, 65, 2))
    rate = max(upper, model)
    return WINDOW * rate, rate


def fresh_steps_needed(V, delta, f):
    """Fresh steps T with 1 - exp(-f tau) - delta >= TARGET, tau = T^2 V / (2N)."""
    tau = -math.log(1 - float(TARGET) - delta) / f
    return math.ceil(math.sqrt(2 * N * tau / float(V)) * (1 + 1e-12))


def build():
    S = MEASURED_S
    s = Fraction(S, R_A)
    V = v_rate(S)
    w, rate = waste_bound(float(s))
    f = 1 - cap_loss(CAP_C)
    lag = WALKS * 2 ** DP_BITS     # detection lag: each walk runs to its next DP before a collision is seen
    # Fixed point: the failure terms depend on the run length, which depends on the failure terms.
    delta = 0.0
    for _ in range(3):
        T = fresh_steps_needed(V, delta, f)
        M = math.ceil((T + lag) / (1 - w))
        delta = derive_failure_terms(M, float(s))["delta"]
    terms = derive_failure_terms(M, float(s))

    adds_per_step = Fraction(NATIVE_ADDS, NATIVE_STEPS)
    sqrs_per_step = Fraction(NATIVE_SQRS, NATIVE_STEPS)
    step_units = adds_per_step + sqrs_per_step * KAPPA + C2
    dps = 2 * M // 2 ** DP_BITS + 2 * WALKS

    # Hard work cutoff: each term is an "at most" that the procedure enforces with its work counter.
    components = {
        "walk_steps": M * step_units,
        "adder_table": R_A * (2 * EXP_UNITS + 12 * FROBENIUS_UNITS),
        # The kernel does not restart at a distinguished point; this charges one restart per DP, which
        # covers every trail-cap or trap restart.
        "walk_starts_and_restarts": (WALKS + dps) * 2 * EXP_UNITS,
        "distinguished_points": Fraction(dps * DP_INSTRUCTIONS, C),
        # Expected pairs of distinct records with equal 128-bit fingerprints, each verified by one exponentiation.
        "fingerprint_verification": Fraction(dps * dps, 2 ** (FINGERPRINT_BITS + 1)) * EXP_UNITS,
        "solve_verify_output": Fraction(SOLVE_INSTRUCTIONS, C),
    }
    W_max = sum(components.values())

    # Success from the work actually available under the cutoff: at least M main steps run, of which a
    # fraction (1 - w) is fresh, less the detection lag.
    tau_eff = float(T) ** 2 * float(V) / (2 * float(N))
    success_model = 1 - math.exp(-f * tau_eff)
    success_lower = success_model - terms["delta"]
    # Loss if the wasted steps were not budgeted: fresh steps (T + lag)(1 - w) - lag.
    success_uncharged = 1 - math.exp(-f * tau_eff * (1 - w) ** 2) - terms["delta"]

    peak_bytes = (dps * DP_BYTES + 12 * R_A * (ELEMENT_BYTES + 2 * EXPONENT_BYTES)
                  + WALKS * (2 * ELEMENT_BYTES + 2 * EXPONENT_BYTES + DETECTOR_BYTES))
    score = exact.log2_up(W_max)
    report = {
        "components_log2_units": {k: round(exact.log2(v), 6) for k, v in components.items()},
        "time_log2": str(score),
        "time_log2_decimal": float(score),
        "time_log2_float": exact.log2(W_max),
        "score_rational": {"numerator": str(score.numerator), "denominator": str(score.denominator)},
        "preprocessing_log2": str(exact.log2_up(components["adder_table"] + components["walk_starts_and_restarts"])),
        "parameters": {
            "N_log2": round(math.log2(N), 6), "square_slots": S, "r_a": R_A, "s": float(s),
            "V": float(V), "walk_steps_T_log2": round(math.log2(T), 6),
            "main_steps_log2": round(math.log2(M), 6), "lag_steps_log2": round(math.log2(lag), 6),
            "distinguished_points_log2": round(math.log2(dps), 6), "dp_bits": DP_BITS, "walks": WALKS,
            "adds_per_step": float(adds_per_step), "sqrs_per_step": float(sqrs_per_step),
            "cycle_events_per_step_bound": rate, "window": WINDOW, "wasted_fraction_charged": w,
            "trail_cap_log2_steps": round(math.log2(CAP), 6), "detection_factor": f,
            "step_units": float(step_units), "false_pairs_log2": round(math.log2(float(components["fingerprint_verification"] / EXP_UNITS)), 6),
            "fingerprint_bits": FINGERPRINT_BITS,
        },
        "failure_terms": terms,
        "memory_log2_bytes": str(exact.log2_up(max(1, peak_bytes))),
        "success": {"tau_eff": tau_eff, "eps": float(1 - V), "model": success_model,
                    "delta": terms["delta"], "lower_bound": success_lower},
        "success_if_waste_not_charged": success_uncharged,
        "c2": float(C2), "kappa": float(KAPPA),
    }
    return report


if __name__ == "__main__":
    print(json.dumps(build(), indent=2))
