"""Toy test of the Frobenius-class GT walk (cscore.gt): success curve, solves, cycle rates.

Input (JSON on stdin): bits (group order ell >= 2^bits), trials, s (square probability
of the mixed walk, 0 for add-only), adder_bits, dp_bits, walks, seed.

Every trial draws a uniform secret y, builds the instance z = g^y, runs the walk
round-robin on the order-ell subgroup of F_{q^12}^* up to the first useful collision,
then solves end to end through distinguished points and checks g^y' = z.

Model under test (RESEARCH.md 3.4-3.5): with N = (ell - 1)/12 classes and collision
rate V = 1 - s^2 - (r_a - S) / r_a^2 with S = s r_a, tau = T^2 V / (2N) is Exp(1) distributed, so
P[tau <= t] = 1 - exp(-t). The experiment reports the empirical CDF of tau against it.

Toy scale only: tests the collision statistics of the walk, not production cost.
"""
import json
import math
import random
import sys
import time

from cscore import gt, stats

TAUS = [0.25, 0.5, 0.5277, 0.75, 1.0, 1.5, 2.0]  # 0.5277 >= tau for model success 0.41 + DELTA


def measurement(rows, G, cfg):
    """Restart, escape and closure measurements. Landings, undos, repeats, duplicate records and escape landings
    over all trials; step shares, chained shares and closure rates over solved trials (first_useful set), as in
    the v9 scratch analysis; fresh-step square share (H9) over all trials."""
    N = (G.m - 1) // gt.DEG
    r_a = 1 << cfg["adder_bits"]
    repeat_rate = 1 / r_a if cfg["restart_rule"] == "v9" else 1 / gt.RESTART_TABLE
    total = lambda rs, key: sum(r[key] for r in rs)
    restarts = total(rows, "restarts")
    landed = total(rows, "landings")
    expected = total(rows, "landings_expected")
    eligible = total(rows, "repeat_eligible")
    repeats = total(rows, "repeats")
    main_steps = sum(sum(r["rounds"]) for r in rows)
    esc = total(rows, "escapes")
    esc_landed = total(rows, "esc_landings")
    esc_expected = total(rows, "esc_landings_expected")
    f_sq, f_add = total(rows, "fresh_square"), total(rows, "fresh_add")
    solved = [r for r in rows if r["first_useful"] is not None]
    s_restarts = total(solved, "restarts")
    s_steps = sum(r["solved_at"] for r in solved if r["solved_at"] is not None)
    n_sq, n_add = total(solved, "n_square"), total(solved, "n_add")
    chained = total(solved, "chained_restart")
    return {
        "all_trials": {
            "trials": len(rows),
            "dp_solved": sum(1 for r in rows if r["correct"]),
            "main_steps": main_steps,
            "restarts": restarts,
            "landings_observed": landed,
            "landings_expected_H8": round(expected, 3),
            "landings_z": round((landed - expected) / expected ** 0.5, 3) if expected else None,
            "undos_observed": total(rows, "undos"),
            "undos_expected_random_1_over_N": round(restarts / N, 3),
            "repeat_eligible": eligible,
            "repeats_observed": repeats,
            "repeat_rate_random": repeat_rate,
            "repeats_expected_random": round(eligible * repeat_rate, 3),
            "dp_events": total(rows, "dp_events"),
            "dp_fresh": total(rows, "dp_fresh"),
            "chained_restarts": total(rows, "chained_restart"),
            "chained_escapes": total(rows, "chained_escape"),
            "dup_records": total(rows, "dup_records"),
            "dup_after_repeat": total(rows, "dup_after_repeat"),
            "dup_after_undo": total(rows, "dup_after_undo"),
            "two_cycle_detections": total(rows, "two_cycles"),
            "anchor_detections": total(rows, "long_cycles"),
            "escapes": esc,
            "escape_landings_observed": esc_landed,
            "escape_landings_expected_H8": round(esc_expected, 3),
            "walk_dp_inside_loop": total(rows, "walk_dp"),
            "closure_rate_per_main_step": round((total(rows, "two_cycles") + total(rows, "long_cycles")) / main_steps, 6),
            "two_cycle_rate_per_main_step": round(total(rows, "two_cycles") / main_steps, 6),
            "anchor_rate_per_main_step": round(total(rows, "long_cycles") / main_steps, 6),
            "fresh_decisions": f_sq + f_add,
            "fresh_square_share": round(f_sq / (f_sq + f_add), 6) if f_sq + f_add else None,
            "coincidences_observed": total(rows, "coincidences"),
            "coincidences_expected_random": round(len(rows) * 2 * gt.RESTART_TABLE * r_a * gt.DEG / G.m, 3),
        },
        "solved_trials": {
            "solved": len(solved),
            "steps": s_steps,
            "restart_steps": s_restarts,
            "restart_fraction_of_steps": round(s_restarts / s_steps, 6) if s_steps else None,
            "escapes": total(solved, "escapes"),
            "escape_fraction_of_steps": round(total(solved, "escapes") / s_steps, 6) if s_steps else None,
            "square_step_decisions": n_sq,
            "additive_step_decisions": n_add,
            "square_share_of_step_decisions": round(n_sq / (n_sq + n_add), 6) if n_sq + n_add else None,
            "square_steps_over_steps": round(n_sq / s_steps, 6) if s_steps else None,
            "chained_restarts": chained,
            "chained_share_of_restarts": round(chained / s_restarts, 6) if s_restarts else None,
        },
    }


def main():
    started = time.time()
    cfg = json.load(sys.stdin)
    for k, v in gt.DEFAULTS.items():
        cfg.setdefault(k, v)
    G = gt.ToyGT(1 << cfg["bits"], seed=cfg["seed"])
    rng = random.Random(cfg["seed"])
    rows = [gt.trial(G, cfg, rng) for _ in range(cfg["trials"])]

    N = (G.m - 1) // gt.DEG
    r_a = 1 << cfg["adder_bits"]
    s_eff = round(cfg["s"] * r_a) / r_a
    S = round(cfg["s"] * r_a)
    V = 1 - s_eff * s_eff - (r_a - S) / r_a ** 2  # additive branches: r_a - S adders, each with probability 1/r_a
    solved = [r for r in rows if r["first_useful"] is not None]
    taus = [r["first_useful"] ** 2 * V / (2 * N) for r in solved]
    m = len(rows)
    cdf = []
    for t in TAUS:
        k = sum(1 for x in taus if x <= t)
        cdf.append({"tau": t, "empirical": round(k / m, 4), "wilson95": stats.wilson(k, m),
                    "model_exp1": round(1 - math.exp(-t), 4)})
    steps = sum(r["solved_at"] or 0 for r in rows)
    out = {
        "group": {"q": G.q, "ell": G.m, "classes_N": N, "lambda": G.lam,
                  "field_modulus_low_coeffs": G.field.f},
        "config": cfg,
        "walk": {"r_a": r_a, "square_slots": round(cfg["s"] * r_a), "s_effective": s_eff,
                 "V": round(V, 6)},
        "trials": m,
        "solved": len(solved),
        "all_solutions_verified": all(r["correct"] for r in solved),
        "mean_tau": round(sum(taus) / len(taus), 4) if taus else None,
        "model_mean_tau": 1.0,
        "success_curve": cdf,
        "mean_detect_overhead_steps": round(sum(r["solved_at"] - r["first_useful"] for r in solved) / len(solved), 2)
        if solved else None,
        "total_steps": steps,
        "two_cycles_per_step": round(sum(r["two_cycles"] for r in rows) / steps, 6) if steps else None,
        "long_cycles_per_step": round(sum(r["long_cycles"] for r in rows) / steps, 6) if steps else None,
        "cycle_step_fraction": round(sum(r["cycle_steps"] for r in rows) / steps, 6) if steps else None,
        "predicted_two_cycles_per_step_RESEARCH_3_5": round((1 - s_eff) ** 2 / (gt.DEG * r_a), 6),
        "restart_rule": cfg["restart_rule"],
        "escape_rule": "v10 replay-invariant (spec section 6)",
        "measurement": measurement(rows, G, cfg),
        "scope": "toy group only; tests the collision statistics and the solver, not production cost",
        "elapsed_seconds": round(time.time() - started, 2),
    }
    print(json.dumps(out))


if __name__ == "__main__":
    main()
