"""Reversed-difference revision: derive this kernel's sources from the predecessor's.

usage: gen11.py <predecessor measurement dir> <output dir>

D = x(W) - x(R) replaces D = x(R) - x(W) in every place the batch forms it
(forward block FLOOP, and the C code for walks 0 and B-1), and t = x3 - x(W)
replaces t = x(W) - x3 in every place the step forms it (backward block
BLOOP_FIELD_S and the C step k_lxy for walk 0). Each edit swaps the two
operands of one four-limb subtraction; the instruction count, registers and
every other line are unchanged. Every edit must match exactly once.
"""
import os
import sys

src, dst = sys.argv[1], sys.argv[2]
EDITS = {
    "floop.h": [
        (r"subs x3,x3,x7\nsbcs x4,x4,x8\nsbcs x5,x5,x14\nsbcs x6,x6,x15",
         r"subs x3,x7,x3\nsbcs x4,x8,x4\nsbcs x5,x14,x5\nsbcs x6,x15,x6"),
    ],
    "bloop_branchy.h": [
        (r"subs x8,x8,x3\nsbcs x9,x9,x4\nsbcs x10,x10,x5\nsbcs x11,x11,x6",
         r"subs x8,x3,x8\nsbcs x9,x4,x9\nsbcs x10,x5,x10\nsbcs x11,x6,x11"),
    ],
    "p256_fused.h": [
        (r"subs x13,x9,x7\nsbcs x14,x10,x8\nsbcs x5,x11,x3\nsbcs x6,x12,x4",
         r"subs x13,x7,x9\nsbcs x14,x8,x10\nsbcs x5,x3,x11\nsbcs x6,x4,x12"),
    ],
    "step.c": [
        ("k_subb_bl(&DP[0].d, &L[0].sel->x, &Wc[0].x);",
         "k_subb_bl(&DP[0].d, &Wc[0].x, &L[0].sel->x);"),
        ("k_subb_bl(&DP[B - 1].d, &L[B - 1].sel->x, &Wc[B - 1].x);",
         "k_subb_bl(&DP[B - 1].d, &Wc[B - 1].x, &L[B - 1].sel->x);"),
        ("k_subm(&acc, &L[B - 1].sel->x, &Wc[B - 1].x, &DP[B - 1].pre);",
         "k_subm(&acc, &Wc[B - 1].x, &L[B - 1].sel->x, &DP[B - 1].pre);"),
    ],
}
for name in ["p256_field.h", "p256_sub.h", "p256_fused.h", "bloop_branchy.h", "floop.h", "step.c"]:
    text = open(os.path.join(src, name)).read()
    for old, new in EDITS.get(name, []):
        assert text.count(old) == 1, (name, old)
        assert old.count("\\n") == new.count("\\n")
        text = text.replace(old, new)
    if name in ("bloop_branchy.h", "floop.h"):
        text = text.replace("/* GENERATED by gen10.py", "/* GENERATED by gen10.py, then gen11.py (reversed D and t)", 1)
    open(os.path.join(dst, name), "w").write(text)
print("ok")
