def wilson(k, m, z=1.96):
    if m == 0:
        return [0.0, 1.0]
    ph = k / m
    den = 1 + z * z / m
    mid = (ph + z * z / (2 * m)) / den
    half = z * math.sqrt(ph * (1 - ph) / m + z * z / (4 * m * m)) / den
    return [round(max(0.0, mid - half), 4), round(min(1.0, mid + half), 4)]


