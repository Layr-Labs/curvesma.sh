"""Toy-curve run of the production rho procedure in trails (escapes to 2*canon(M), cscore.rho_sigma.Walk).

Input (JSON on stdin):
  curve: "a3" (y^2 = x^3 - 3x + b, negation classes, key = Montgomery x; P-256 shape)
  bits (of p), trials, adder_bits, dp_bits, walks, seed, tau_e4 (budget tau * 10^4),
  adder_key_shift (adders redrawn until key < p >> shift; 0 = uniform adders)
  escape: "double" (the only mode; escape to 2*canon(M))

Every trial samples a uniform secret and runs the procedure to its end at the budget:
- trails from fresh coins, with no coefficient tracking while walking;
- a slot restarts at each distinguished point;
- L steps per slot, then each slot finishes its current trail;
- the first key match replays both trails from their coins;
- a degenerate match is a failure.
It reports the success rate against 1 - exp(-tau).

Toy scale only: tests the procedure and its collision statistics, not production cost.
"""
import json
import random
import sys

from cscore import groups, rho_sigma, rho_trails


def main():
    cfg = json.load(sys.stdin)
    for k, v in rho_trails.DEFAULTS.items():
        cfg.setdefault(k, v)
    cfg.setdefault("curve", "a3")
    if cfg.setdefault("escape", "double") != "double":
        raise SystemExit("escape must be \"double\"")
    rng = random.Random(cfg["seed"])
    if cfg["curve"] == "a3":
        E, G, n = groups.find_prime_order_curve(cfg["bits"], rng)
        cls = rho_sigma.NegationX(E.p, n)
        curve = {"p": E.p, "a": E.a, "b": E.b, "order": n}
    else:
        raise SystemExit("curve must be a3")
    out = {"curve": curve, "config": cfg}
    out.update(rho_trails.run(E, G, n, cls, cfg, rng))
    out["scope"] = "toy curves only; runs the production procedure including resolution, not production cost"
    print(json.dumps(out))


if __name__ == "__main__":
    main()
