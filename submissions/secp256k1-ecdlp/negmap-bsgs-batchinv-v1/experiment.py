"""Finite-scope checks for the secp256k1 streamed negation-map BSGS package (proof.md).

Evidence only at the stated scope. Nothing here executes production P-256
attack work, allocates the exponential storage, times anything, or proves the
production cost bound; that bound is analytic (proof.md).

Modes:
  additive - signed-window coverage/sign logic on Z/nZ (class key min(v,n-v)).
  jacobian - complete mixed Jacobian addition and the a=0 doubling
             (dbl-2009-l) versus complete affine addition, on small prime-order
             a=0 (j=0) curves, generic-a curves and the real secp256k1 generator.
  batch    - zero-safe Montgomery prefix/reverse batch normalization versus
             per-point affine conversion, including infinity (Z=0) entries.
  stream   - the full streamed algorithm on small prime-order curves: both
             progressions generated by mixed Jacobian steps, batch-normalized
             in blocks, emitted in key order by an explicit lazy binary merge
             tree, intersected at the root with the stored-y sign decision and
             verified. Checks exact coverage, recovery of every covered scalar,
             no wrong output, sorted emission, each record emitted once, and
             per-record merge-level crossings = tree depth.
  kernel   - the exact 4x64-bit CIOS Montgomery multiplication of proof.md over
             the real secp256k1 field with its instruction tally, and the Fermat
             inversion chain for p-2.
  ledger   - exact integer checks of coverage vs the real secp256k1 order r and of
             the instruction ledger against the submitted rational bound.
"""
import json
import sys

SECP_P = 0xfffffffffffffffffffffffffffffffffffffffffffffffffffffffefffffc2f
SECP_R = 0xfffffffffffffffffffffffffffffffebaaedce6af48a03bbfd25e8cd0364141
SECP_A = 0
SECP_B = 7
SECP_GX = 0x79be667ef9dcbbac55a06295ce870b07029bfcdb2dce28d959f2815b16f81798
SECP_GY = 0x483ada7726a3c4655da4fbfc0e1108a8fd17b448a68554199c47d08ffb10d4b8
MASK = (1 << 64) - 1

# Ledger allowances (proof.md), scalar AArch64 instructions.
M_BUDGET = 384           # field multiplication / squaring
A_BUDGET = 64            # field add / sub / negate / compare
I_BUDGET = 1 << 19       # Fermat inversion (covers 512 multiplications + control)
BLOCK = 4096             # batch-normalization block size
U_WRITE = 1 << 17        # routed record write to its leaf
INIT_NODE = 57344        # per storage/merge node initialization
DEPTH = 127              # tree depth (2^127 leaves per list)
ROOT_REC = 1 << 14       # root intersection per giant record
OUTER = 4096             # per generated record outer-loop allowance
FIXED = 1 << 40          # setup, validation, verification, output
SCORE_NUM, SCORE_DEN = 13669154, 100000   # submitted time_log2 = 136.69154


def plan(n, m):
    s = 2 * m - 1
    c = m - 1
    h = n // s
    return s, c, h


def additive(n, m):
    s, c, h = plan(n, m)
    key = lambda v: min(v % n, (-v) % n)
    table = {}
    for j in range(m):
        k = key(j)
        assert k not in table
        table[k] = j
    covered = h * s
    recovered = 0
    for x in range(n):
        out = None
        for i in range(h):
            t = (x - i * s - c) % n
            k = key(t)
            if k in table:
                j = table[k]
                for a in ((i * s + c + j) % n, (i * s + c - j) % n):
                    if a == x:
                        out = a
                break
        if x < covered:
            assert out == x, ("covered scalar not recovered", n, m, x)
            recovered += 1
        else:
            assert out is None, ("uncovered scalar returned a value", n, m, x)
    return {"order": n, "m": m, "covered": covered, "recovered": recovered,
            "exact_coverage": recovered == covered}


# ---------------- affine reference arithmetic ----------------
def make_affine(p, a):
    def add(P, Q):
        if P is None:
            return Q
        if Q is None:
            return P
        if P[0] == Q[0] and (P[1] + Q[1]) % p == 0:
            return None
        if P == Q:
            num = (3 * P[0] * P[0] + a) % p
            den = (2 * P[1]) % p
        else:
            num = (Q[1] - P[1]) % p
            den = (Q[0] - P[0]) % p
        l = num * pow(den, p - 2, p) % p
        x3 = (l * l - P[0] - Q[0]) % p
        return (x3, (l * (P[0] - x3) - P[1]) % p)

    def mul(k, P):
        R = None
        while k:
            if k & 1:
                R = add(R, P)
            P = add(P, P)
            k >>= 1
        return R
    return add, mul


# ---------------- Jacobian arithmetic (proof.md) ----------------
# Jacobian (X,Y,Z) represents (X/Z^2, Y/Z^3); Z=0 is infinity.
def jac_dbl(R, p, a):
    X, Y, Z = R
    if Z == 0 or Y == 0:
        return (1, 1, 0)
    if a % p == 0:
        # dbl-2009-l, a=0: 2M + 5S
        A = X * X % p
        B = Y * Y % p
        C = B * B % p
        D = 2 * ((X + B) * (X + B) % p - A - C) % p
        E = 3 * A % p
        F = E * E % p
        X3 = (F - 2 * D) % p
        Y3 = (E * (D - X3) - 8 * C) % p
        Z3 = 2 * Y * Z % p
        return (X3, Y3, Z3)
    if a % p == (p - 3) % p:
        delta = Z * Z % p
        gamma = Y * Y % p
        beta = X * gamma % p
        alpha = 3 * (X - delta) * (X + delta) % p
        X3 = (alpha * alpha - 8 * beta) % p
        Z3 = ((Y + Z) * (Y + Z) - gamma - delta) % p
        Y3 = (alpha * (4 * beta - X3) - 8 * gamma * gamma) % p
        return (X3, Y3, Z3)
    XX = X * X % p
    YY = Y * Y % p
    ZZ = Z * Z % p
    S = 4 * X * YY % p
    Mv = (3 * XX + a * ZZ * ZZ) % p
    X3 = (Mv * Mv - 2 * S) % p
    Y3 = (Mv * (S - X3) - 8 * YY * YY) % p
    Z3 = 2 * Y * Z % p
    return (X3, Y3, Z3)


def jac_madd(R, Q2, p, a):
    """Complete mixed addition R (Jacobian) + Q2 (affine or None)."""
    if Q2 is None:
        return R
    x2, y2 = Q2
    X1, Y1, Z1 = R
    if Z1 == 0:
        return (x2, y2, 1)
    Z1Z1 = Z1 * Z1 % p
    U2 = x2 * Z1Z1 % p
    S2 = y2 * Z1 * Z1Z1 % p
    H = (U2 - X1) % p
    rr = (S2 - Y1) % p
    if H == 0:
        if rr == 0:
            return jac_dbl(R, p, a)
        return (1, 1, 0)
    HH = H * H % p
    HHH = H * HH % p
    V = X1 * HH % p
    X3 = (rr * rr - HHH - 2 * V) % p
    Y3 = (rr * (V - X3) - Y1 * HHH) % p
    Z3 = Z1 * H % p
    return (X3, Y3, Z3)


def to_affine(R, p):
    X, Y, Z = R
    if Z == 0:
        return None
    zi = pow(Z, p - 2, p)
    return (X * zi * zi % p, Y * zi * zi * zi % p)


def batch_normalize(pts, p):
    """Zero-safe Montgomery prefix/reverse inversion; returns affine points.
    Z=0 entries are replaced by 1 in the product chain and restored as
    infinity via their flag, exactly as described in proof.md."""
    n = len(pts)
    flags = [R[2] == 0 for R in pts]
    zs = [1 if f else R[2] for R, f in zip(pts, flags)]
    pref = [0] * n
    acc = 1
    for k in range(n):
        acc = acc * zs[k] % p          # 1M per element
        pref[k] = acc
    inv = pow(acc, p - 2, p)           # one inversion per block
    out = [None] * n
    for k in range(n - 1, -1, -1):
        zinv = inv * (pref[k - 1] if k > 0 else 1) % p   # 1M
        inv = inv * zs[k] % p                            # 1M
        if flags[k]:
            out[k] = None
            continue
        zi2 = zinv * zinv % p                            # 1S
        X, Y, _ = pts[k]
        out[k] = (X * zi2 % p, Y * zi2 * zinv % p)       # x needs 1M
    return out


def is_prime(n):
    return n > 1 and all(n % d for d in range(2, int(n ** 0.5) + 1))


def small_curve(p, a, b):
    if (4 * a ** 3 + 27 * b * b) % p == 0:
        return None
    pts = [(x, y) for x in range(p) for y in range(p)
           if (y * y - x ** 3 - a * x - b) % p == 0]
    n = len(pts) + 1
    if not is_prime(n):
        return None
    return pts, n


def curve_list(max_per_field=2):
    out = []
    # a = 0 (secp256k1 / j=0 shape)
    for p in (101, 103, 107, 109, 113, 127, 131):
        found = 0
        for b in range(1, p):
            sc = small_curve(p, 0, b)
            if sc and sc[1] >= 31:
                out.append(("a=0", p, 0, b, sc))
                found += 1
                if found == max_per_field:
                    break
    # also a=-3 and generic for formula coverage
    for p in (101, 107, 113):
        found = 0
        for b in range(1, p):
            sc = small_curve(p, (p - 3) % p, b)
            if sc and sc[1] >= 31:
                out.append(("a=-3", p, (p - 3) % p, b, sc))
                found += 1
                if found == 1:
                    break
    for p in (101, 107, 113):
        for a in (2, 5, 7):
            for b in range(1, p):
                sc = small_curve(p, a, b)
                if sc and sc[1] >= 31:
                    out.append(("generic", p, a, b, sc))
                    break
    return out


def jacobian_checks():
    runs = 0
    ok = True
    for fam, p, a, b, (pts, n) in curve_list():
        add, mul = make_affine(p, a)
        G = pts[0]
        # progression R_{k+1} = R_k + G in Jacobian vs affine, through infinity
        R = (1, 1, 0)
        A_ = None
        for k in range(2 * n + 3):
            ok &= (to_affine(R, p) == A_)
            R = jac_madd(R, G, p, a)
            A_ = add(A_, G)
        # doubling branch and opposite branch
        for P_ in pts[:20]:
            J = (P_[0], P_[1], 1)
            ok &= to_affine(jac_madd(J, P_, p, a), p) == add(P_, P_)
            ok &= to_affine(jac_madd(J, (P_[0], (-P_[1]) % p), p, a), p) is None
        runs += 1
    # real secp256k1 generator: a few mixed steps and a doubling, a=0 path
    p = SECP_P
    add, _ = make_affine(p, SECP_A)
    G = (SECP_GX, SECP_GY)
    R = (1, 1, 0)
    A_ = None
    for k in range(8):
        ok &= (to_affine(R, p) == A_)
        R = jac_madd(R, G, p, SECP_A)
        A_ = add(A_, G)
    ok &= to_affine(jac_dbl((SECP_GX, SECP_GY, 1), p, SECP_A), p) == add(G, G)
    return {"small_curves": runs, "secp_generator_checked": True,
            "jacobian_matches_affine": bool(ok)}


def batch_checks():
    ok = True
    total = 0
    for fam, p, a, b, (pts, n) in curve_list():
        add, mul = make_affine(p, a)
        G = pts[0]
        seq = []
        R = (1, 1, 0)
        for k in range(n + 5):        # includes the infinity entries k=0, n
            seq.append(R)
            R = jac_madd(R, G, p, a)
        for blk in (1, 3, 4, 7):
            for st in range(0, len(seq), blk):
                chunk = seq[st:st + blk]
                ok &= batch_normalize(chunk, p) == [to_affine(R_, p) for R_ in chunk]
                total += len(chunk)
    return {"entries_checked": total, "batch_matches_direct": bool(ok)}


# ---------------- explicit lazy binary merge tree ----------------
class Leaf:
    def __init__(self, rec):
        self.rec = rec
        self.done = rec is None

    def head(self):
        return None if self.done else self.rec

    def pop(self, cross):
        r = self.rec
        self.done = True
        return r


class Node:
    """Caches one head per child, emits the smaller key (left-first on ties).
    Every emitted record crosses this node's parent edge exactly once."""
    def __init__(self, left, right):
        self.L, self.R = left, right

    def head(self):
        a, b = self.L.head(), self.R.head()
        if a is None:
            return b
        if b is None:
            return a
        return a if a[0] <= b[0] else b

    def pop(self, cross):
        a, b = self.L.head(), self.R.head()
        if a is not None and (b is None or a[0] <= b[0]):
            r = self.L.pop(cross)
        else:
            r = self.R.pop(cross)
        cross[r[1]] = cross.get(r[1], 0) + 1
        return r


def build_tree(records, depth):
    leaves = [Leaf(r) for r in records] + [Leaf(None)] * ((1 << depth) - len(records))
    level = leaves
    for _ in range(depth):
        level = [Node(level[2 * k], level[2 * k + 1]) for k in range(len(level) // 2)]
    return level[0]


def stream(tree):
    cross = {}
    out = []
    while tree.head() is not None:
        out.append(tree.pop(cross))
    return out, cross


def stream_curve(fam, p, a, b, pts, n, m, blk):
    add, mul = make_affine(p, a)
    G = pts[0]
    s, c, h = plan(n, m)
    INF = (-1,)   # infinity key sorts first, separate from every x
    key = lambda A: INF if A is None else (A[0],)
    depth_b = max(1, (m - 1).bit_length())
    depth_g = max(1, (h - 1).bit_length())

    # Baby progression jP by mixed Jacobian steps, batch-normalized in blocks.
    jac = []
    R = (1, 1, 0)
    for j in range(m):
        jac.append(R)
        R = jac_madd(R, G, p, a)
    aff = []
    for st in range(0, m, blk):
        aff += batch_normalize(jac[st:st + blk], p)
    baby = [(key(A_), ("b", j), A_) for j, A_ in enumerate(aff)]
    assert len({r[0] for r in baby}) == m, "duplicate baby key"
    btree_out, bcross = stream(build_tree(baby, depth_b))
    assert [r[0] for r in btree_out] == sorted(r[0] for r in baby)
    assert all(v == depth_b for v in bcross.values()) and len(bcross) == m

    D = mul((n - s) % n, G)
    covered = h * s
    recovered = 0
    for x in range(n):
        Q = mul(x, G)
        g0 = add(Q, mul((n - c) % n, G))
        gj = []
        Rg = (1, 1, 0) if g0 is None else (g0[0], g0[1], 1)
        for i in range(h):
            gj.append(Rg)
            Rg = jac_madd(Rg, D, p, a)
        gaff = []
        for st in range(0, h, blk):
            gaff += batch_normalize(gj[st:st + blk], p)
        giant = [(key(A_), ("g", i), A_) for i, A_ in enumerate(gaff)]
        gout, gcross = stream(build_tree(giant, depth_g))
        assert [r[0] for r in gout] == sorted(r[0] for r in giant)
        assert all(v == depth_g for v in gcross.values()) and len(gcross) == h
        # Root intersection of the two sorted streams.
        out = None
        bi = 0
        for rec in gout:
            while bi < m and btree_out[bi][0] < rec[0]:
                bi += 1
            if bi < m and btree_out[bi][0] == rec[0]:
                j = btree_out[bi][1][1]
                i = rec[1][1]
                Rj = btree_out[bi][2]
                plus = (Rj == rec[2])
                cand = (i * s + c + j) % n if plus else (i * s + c - j) % n
                if mul(cand, G) == Q:
                    out = cand
                    break
        if x < covered:
            assert out == x, ("stream: covered scalar not recovered", p, a, b, x)
            recovered += 1
        else:
            assert out is None or mul(out, G) == Q
    return {"family": fam, "field": p, "a": a, "b": b, "order": n, "m": m,
            "h": h, "block": blk, "covered": covered, "recovered": recovered,
            "exact_coverage": recovered == covered}


def stream_runs():
    runs = []
    for fam, p, a, b, (pts, n) in curve_list(max_per_field=1):
        runs.append(stream_curve(fam, p, a, b, pts, n, 4, 3))
    return runs


# ---------------- CIOS Montgomery multiplication with tally ----------------
class Tally:
    def __init__(self):
        self.n = 0

    def __call__(self, k=1):
        self.n += k


def mont_mul(a, b, p, n0, t_):
    A = [(a >> (64 * i)) & MASK for i in range(4)]
    B = [(b >> (64 * i)) & MASK for i in range(4)]
    P = [(p >> (64 * i)) & MASK for i in range(4)]
    t_(8)  # LDR a[0..3], b[0..3]
    t_(4)  # materialize p limbs
    T = [0] * 6
    for i in range(4):
        C = 0
        for j in range(4):
            prod = A[j] * B[i]
            t_(2)                     # MUL, UMULH
            s = T[j] + (prod & MASK) + C
            t_(3)                     # ADDS lo, ADC hi, ADDS carry-in
            T[j] = s & MASK
            C = (prod >> 64) + (s >> 64)
            t_(1)                     # ADC carry-out
        s = T[4] + C
        T[4] = s & MASK
        T[5] = s >> 64
        t_(2)
        mq = (T[0] * n0) & MASK
        t_(1)
        C = 0
        for j in range(4):
            prod = mq * P[j]
            t_(2)
            s = T[j] + (prod & MASK) + C
            t_(3)
            T[j] = s & MASK
            C = (prod >> 64) + (s >> 64)
            t_(1)
        s = T[4] + C
        T[4] = s & MASK
        T[5] += s >> 64
        t_(2)
        T = T[1:6] + [0]
        t_(5)
    val = sum(T[i] << (64 * i) for i in range(5))
    t_(5)
    if val >= p:
        val -= p
    t_(4)
    t_(4)
    t_(24)
    return val


def kernel(trials=300):
    p = SECP_P
    n0 = (-pow(p, -1, 1 << 64)) % (1 << 64)
    Rm = 1 << 256
    Rinv = pow(Rm, -1, p)
    seed = 0x5eed
    worst = 0
    ok = True
    for k in range(trials):
        seed = (seed * 6364136223846793005 + 1442695040888963407) % (1 << 64)
        a = pow(seed, 7, p)
        b = pow(seed + 1, 11, p)
        if k == 0:
            a, b = p - 1, p - 1
        t = Tally()
        got = mont_mul(a, b, p, n0, t)
        ok &= (got == a * b * Rinv % p) and got < p
        worst = max(worst, t.n)
    e = p - 2
    squarings = e.bit_length() - 1
    multiplies = bin(e).count("1") - 1
    t = Tally()
    x = (SECP_GX * Rm) % p
    acc = x
    for bit in bin(e)[3:]:
        acc = mont_mul(acc, acc, p, n0, t)
        if bit == "1":
            acc = mont_mul(acc, x, p, n0, t)
    inv_ok = (acc * Rinv % p) * SECP_GX % p == 1
    on_curve = (SECP_GY ** 2 - SECP_GX ** 3 - SECP_A * SECP_GX - SECP_B) % p == 0
    fermat_instr = t.n
    return {"field": "secp256k1", "n0_prime": n0, "trials": trials,
            "mont_mul_correct": bool(ok),
            "mont_mul_worst_tally_instructions": worst,
            "mont_mul_budget_charged": M_BUDGET,
            "mont_mul_within_budget": worst <= M_BUDGET,
            "fermat_squarings": squarings, "fermat_multiplies": multiplies,
            "fermat_total_mults": squarings + multiplies,
            "fermat_tallied_instructions": fermat_instr,
            "inversion_budget_charged": I_BUDGET,
            "inversion_within_budget": fermat_instr + (1 << 14) <= I_BUDGET,
            "fermat_chain_inverts": bool(inv_ok),
            "generator_on_curve": bool(on_curve)}


def ledger():
    r = SECP_R
    m = 1 << 127
    s, c, h = 2 * m - 1, m - 1, 1 << 127
    cov = h * s
    JAC = 16 * M_BUDGET + 32 * A_BUDGET + 4096
    NORM = 7 * M_BUDGET + 4096 + I_BUDGET // BLOCK
    E = JAC + NORM
    G = E + U_WRITE + OUTER
    S = 1024 * (DEPTH + 2) + 4096
    nodes = 4 * m
    comp = {
        "fixed": FIXED,
        "tree_init": nodes * INIT_NODE,
        "baby_generate_normalize_write": m * G,
        "giant_generate_normalize_write": h * G,
        "merge_streams": (m + h) * S,
        "root_intersection": h * ROOT_REC,
    }
    T = sum(comp.values())
    lhs = T ** SCORE_DEN
    rhs = (1000 ** SCORE_DEN) * (1 << SCORE_NUM)
    # tightness: the next lower quarter fails
    rhs_lower = (1000 ** SCORE_DEN) * (1 << (SCORE_NUM - 1))
    return {"coverage": str(cov), "coverage_below_r": cov < r,
            "twice_coverage_above_r": 2 * cov > r,
            "no_duplicate_baby_keys_m_minus_1_below_r_half": m - 1 < r // 2,
            "allowances": {"M": M_BUDGET, "A": A_BUDGET, "I": I_BUDGET,
                           "JAC": JAC, "NORM": NORM, "E": E, "G": G, "S": S,
                           "INIT": INIT_NODE, "ROOT": ROOT_REC},
            "components": {k: str(v) for k, v in comp.items()},
            "T": str(T),
            "T_pow_den_below_1000pow_den_2pow_num": lhs < rhs,
            "tight_next_lower_fails": not (T ** SCORE_DEN < (1000 ** SCORE_DEN) * (1 << (SCORE_NUM - 1))),
            "score": "%d/%d" % (SCORE_NUM, SCORE_DEN)}


def main():
    cfg = json.load(sys.stdin)
    mode = cfg.get("mode", "all")
    res = {"scope": "toy groups, one real-field kernel model and exact integer "
                    "checks; does not validate production cost bounds"}
    if mode in ("all", "additive"):
        runs = []
        for n in (101, 257, 521, 1009):
            for m in (2, 4, 8, 16):
                if 2 * m - 1 <= n:
                    runs.append(additive(n, m))
        res["additive_runs"] = len(runs)
        res["additive_all_exact"] = all(x["exact_coverage"] for x in runs)
    if mode in ("all", "jacobian"):
        res["jacobian"] = jacobian_checks()
    if mode in ("all", "batch"):
        res["batch"] = batch_checks()
    if mode in ("all", "stream"):
        runs = stream_runs()
        res["stream"] = runs
        res["stream_runs"] = len(runs)
        res["stream_all_exact"] = all(x["exact_coverage"] for x in runs)
    if mode in ("all", "kernel"):
        res["kernel"] = kernel()
    if mode in ("all", "ledger"):
        res["ledger"] = ledger()
    print(json.dumps(res))


if __name__ == "__main__":
    main()
