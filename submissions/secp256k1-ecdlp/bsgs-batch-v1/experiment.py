#!/usr/bin/env python3
"""Supporting evidence for the batched-inversion BSGS candidate.

This runs at toy scale only. It checks two things that the analytic argument
asserts and that a reviewer can verify independently:

  1. baby-step/giant-step scalar recovery is correct and deterministic
     (success 1 on every instance generated here);
  2. Montgomery batch inversion returns exactly the per-element inverses,
     which is the amortisation the cost ledger relies on.

It does not measure production cost, memory or wall-clock behaviour, and its
output is not evidence about the 2^128-step instance.
"""
import json
import random
import sys
from math import isqrt


def inv(a, p):
    return pow(a, -1, p)


def batch_inv(values, p):
    """Montgomery's trick: one inversion, 3(n-1) multiplications."""
    n = len(values)
    prefix = [1] * n
    acc = 1
    for i in range(n):
        prefix[i] = acc
        acc = acc * values[i] % p
    inv_acc = inv(acc, p)
    out = [0] * n
    for i in range(n - 1, -1, -1):
        out[i] = inv_acc * prefix[i] % p
        inv_acc = inv_acc * values[i] % p
    return out


def point_add(P, Q, p):
    if P is None:
        return Q
    if Q is None:
        return P
    x1, y1 = P
    x2, y2 = Q
    if x1 == x2 and (y1 + y2) % p == 0:
        return None
    if P == Q:
        s = (3 * x1 * x1) * inv(2 * y1, p) % p
    else:
        s = (y2 - y1) * inv(x2 - x1, p) % p
    x3 = (s * s - x1 - x2) % p
    return (x3, (s * (x1 - x3) - y1) % p)


def point_mul(k, P, p):
    R = None
    while k:
        if k & 1:
            R = point_add(R, P, p)
        P = point_add(P, P, p)
        k >>= 1
    return R


def curve_order(p):
    """#E(F_p) for y^2 = x^3 + 7, by direct enumeration (toy primes only)."""
    count = 1  # point at infinity
    for x in range(p):
        rhs = (x * x * x + 7) % p
        if rhs == 0:
            count += 1
            continue
        # Euler criterion
        if pow(rhs, (p - 1) // 2, p) == 1:
            count += 2
    return count


def factor(n):
    fs = []
    d = 2
    while d * d <= n:
        if n % d == 0:
            fs.append(d)
            while n % d == 0:
                n //= d
        d += 1
    if n > 1:
        fs.append(n)
    return fs


def find_generator(p, n):
    """A point of maximal order on y^2 = x^3 + 7 over F_p (toy primes only)."""
    best = None
    best_ord = 0
    tried = 0
    for x in range(p):
        rhs = (x * x * x + 7) % p
        if rhs == 0:
            P = (x, 0)
        elif pow(rhs, (p - 1) // 2, p) == 1:
            y = None
            if p % 4 == 3:
                y = pow(rhs, (p + 1) // 4, p)
            else:
                for cand in range(p):
                    if cand * cand % p == rhs:
                        y = cand
                        break
            if y is None:
                continue
            P = (x, y)
        else:
            continue
        tried += 1
        d = order_of_point(P, n, p)
        if d > best_ord:
            best, best_ord = P, d
        if best_ord == n or tried >= 256:
            break
    if best is None:
        raise RuntimeError("no point found")
    return best


def bsgs(Q, G, r, p, m):
    """Deterministic BSGS on the subgroup generated by G of order r."""
    if Q is None:
        return 0
    table = {}
    cur = None
    for j in range(m):
        if cur is not None:
            table[cur[0]] = j
        cur = point_add(cur, G, p)
    mP = cur  # [m]G, non-identity because 0 < m < r
    gamma = Q
    D = (mP[0], (-mP[1]) % p)
    for i in range(-(-r // m) + 1):
        if gamma is None:
            for cand in (i * m % r, (-i * m) % r):
                if point_mul(cand, G, p) == Q:
                    return cand
        elif gamma[0] in table:
            j = table[gamma[0]]
            for cand in ((i * m + j) % r, (i * m - j) % r):
                if point_mul(cand, G, p) == Q:
                    return cand
        gamma = point_add(gamma, D, p)
    return None


def order_of_point(G, n, p):
    """Exact order of G given a multiple n of it (toy sizes only)."""
    d = n
    for f in factor(n):
        while d % f == 0 and point_mul(d // f, G, p) is None:
            d //= f
    return d


def main():
    req = json.load(sys.stdin)
    p = int(req.get("prime", 1009))
    trials = int(req.get("trials", 16))
    if not (7 <= p <= 100003):
        raise SystemExit("prime out of range")

    n = curve_order(p)
    G = find_generator(p, n)
    r = order_of_point(G, n, p)
    m = isqrt(r) + 1
    if m >= r:
        m = max(2, r - 1)
    rng = random.Random(20261104)
    successes = 0
    checks = []
    for _ in range(trials):
        x = rng.randrange(r)
        Q = point_mul(x, G, p)
        got = bsgs(Q, G, r, p, m)
        ok = got is not None and point_mul(got, G, p) == Q
        successes += 1 if ok else 0
        checks.append({"x": x, "recovered": got, "ok": ok})

    # batch inversion must agree with independent per-element inversion
    vals = [v for v in range(1, 65)]
    prod = 1
    for v in vals:
        prod = prod * v % p
    if prod % p == 0:
        vals = [v for v in range(2, 66)]
    batched = batch_inv(vals, p)
    batch_ok = all(batched[i] * vals[i] % p == 1 for i in range(len(vals)))

    out = {
        "prime": p,
        "curve": "y^2 = x^3 + 7",
        "group_order": n,
        "subgroup_order_r": r,
        "bsgs_m": m,
        "trials": trials,
        "successes": successes,
        "success_rate": successes / trials if trials else 0.0,
        "batch_inversion_matches_pow": batch_ok,
        "scope": "toy scale only; does not establish production cost or memory",
        "sample": checks[:4],
    }
    json.dump(out, sys.stdout, indent=2)
    sys.stdout.write("\n")


if __name__ == "__main__":
    main()
