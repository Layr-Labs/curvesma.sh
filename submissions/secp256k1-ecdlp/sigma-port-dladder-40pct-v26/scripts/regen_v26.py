        "R=32, production class key, lag-3 escape: {cells}. The best measured cell is d=0 at {best} CP-95, which "
        "is BELOW {floor}, and the direct count collapses with the gate density the way the production gate "
        "requires: by d=16 it is 0/1200. Production runs at d=60. NO cell therefore supports a production success "
        "floor, and none is asserted. "
        "WHAT WAS DELETED, and why. (1) The exp-of-mean substitution: f(T)=(1-p)^T is convex, so E[(1-p)**T] >= "
        "(1-p)**E[T] and the v24 number was an upper bound on success, not the success. (2) The exact-sum ratio "
        "correction R: its T was total visits across ALL lanes before the first solve or budget exhaustion, a "
        "STOPPING TIME, and 1/mean(T) is not the DP density 2**-60 -- that statistic did not measure the recovery "
        "event and could not be rescaled into one, so R is withdrawn rather than repaired. (3) The bootstrap "
        "interval and the pooled 3600-trial CP bound: pooling cells is forbidden by the earlier verdict and the "
