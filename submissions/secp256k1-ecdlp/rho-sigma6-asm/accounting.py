"""Exact accounting for the claim in proof.md (stdlib only; prints JSON).

All work is converted to target-group-operation equivalents. The walk does not use the
6M reference operation: every scalar AArch64 instruction of the attack, including all
field arithmetic (secp_field.h, secp_sub.h), is charged at 1/C, C=1000. Integers and rationals are exact; logarithms are rounded
up to 6 decimals.
"""
import json
import math
import os
from fractions import Fraction

from cscore.exact import Ledger, iroot_ceil, log2, log2_up

r = 0xfffffffffffffffffffffffffffffffebaaedce6af48a03bbfd25e8cd0364141
LAMBDA = 0x5363ad4cc05c30e0a5261c028812645a122e22ea20816678df02967c1b23bd72   # proof.md section 1.1
assert pow(LAMBDA, 3, r) == 1 and LAMBDA != 1          # lambda is a primitive cube root of unity mod r
C = 1000
ADDERS = 2 ** 16             # r-adding walk; index = bits 1..16 of the class key
K = 2 ** 32                  # walks (2^16 processors x 2^16-walk batches)
THETA_BITS = 60              # distinguished-point probability 2^-60
# A trail ends at its first distinguished point. A trail that crosses more than 2^60 anchor
# boundaries (64 steps apart) without one is abandoned, so every trail has fewer than
# TRAIL_MAX steps.
CAP = 64 * 2 ** THETA_BITS
TRAIL_MAX = CAP + 64

# Classes: N nonzero order-6 classes, plus one for the identity (never reached by a walk).
N = (r - 1) // 6 + 1

# Success model (proof.md section 2): 1 - exp(-tau*(1-eps)) - delta with tau = T^2/(2N).
# 2-cycles at most 1/A (Lemma C gives 1/(6 A)), 3..64-cycles at most 3/A^2 (Lemma C).
eps = Fraction(4, ADDERS) + 2 * Fraction(3, ADDERS) + 2 * Fraction(3 * 192, ADDERS ** 2)
delta = Fraction(1, 2 ** 20)
TAU_TARGET = Fraction(5303, 10000)
T_min = iroot_ceil(math.ceil(2 * N * TAU_TARGET), 2)
L = -(-T_min // K)                 # steps per walk counted towards the collision budget
T = K * L
S_max = K * (L + TRAIL_MAX)        # worst case: after L steps each walk finishes its current trail


# Forced-path worst cases (Ir per call; secp/forced/results.json). Every unbatched operation of a rare
# path is charged its worst case, so no per-call average enters the charge.
F_MAX = 23354        # f_single: adder selection (with its rotation fallback where present) and the addition
ADD_MAX = 23079    # add_single
SAME_MAX = 70  # same_class
PDP_MAX = 41    # point_is_dp
ESC2_MAX = 23550  # escape of a 2-cycle (least-key member, canon, doubling)
ESC65_MAX = 26448  # escape of a 65-cycle
OVERHEAD = 1024    # control overhead per rare event and per look-ahead step (measured: far below this)
UNBATCHED = F_MAX  # unit for scalar multiplications and replays: an upper bound for an addition or doubling
# Charge per walk step (proof section 3): the measured common-path count of a batch, taking the larger of
# the plain and anchor steps. The anchor batch of this package does not contain a rare event; if it does, the
# charge double-counts that event, which is conservative.
C_COMMON = 821      # measured anchor step 818.66 + 2 for the canon_pick branch (k_max = 2), rounded up
MAX_LOOK = 64      # look-ahead steps per anchor check (MAX_CYCLE)
# Metered rare events (proof.md, Lemma M). W_CHECK: one 2-cycle check (f_single, same_class, escape,
# point_is_dp, overhead). W_ENTRY: one anchor check with its look-ahead steps (f_single, escape of up to 65
# members, up to 64 look-ahead steps, each f_single, point_is_dp and same_class, with overhead).
W_CHECK = F_MAX + SAME_MAX + ESC2_MAX + PDP_MAX + OVERHEAD
W_ENTRY = F_MAX + ESC65_MAX + MAX_LOOK * (F_MAX + PDP_MAX + SAME_MAX + OVERHEAD) + OVERHEAD
GAMMA = 6                                     # |Gamma|: signs and powers of lambda
RATE_TWO = Fraction(1, GAMMA * ADDERS)       # 2-cycle closure per step: Lemma C' (M1), exact
RATE_LONG = Fraction(3, ADDERS ** 2)         # 3..64-cycle closure per step: c = 3 (Lemma C' derives c <= 0.15; 3 kept)
RATE_FALSE = Fraction(1, 2 ** 63)            # false 63-bit filter match (rejected by the exact check)
RATE_FALLBACK = Fraction(1, 2 ** 55)         # exact-k fallback per canon call (M1 extended to the coordinate fractions)
F_EXACT = 256                                # worst case of one fallback: the whole canon call with the fallback taken
                                             # (static bound 253 for canon_k with fallback; canon_k_exact 197 inside it)
# Within-trail coincidence per walk step (proof.md section 6): |Gamma| TRAIL_MAX (1/r + 1/(r - |Gamma| TRAIL_MAX)).
RATE_COINC = GAMMA * TRAIL_MAX * (Fraction(2, r) + Fraction(1, r - GAMMA * TRAIL_MAX ** 2 // 2))  # MODEL-r8 v3, Lemma G
EVENTS = [
    ("two_cycle_checks", RATE_TWO + RATE_FALSE, W_CHECK),
    ("anchor_checks", RATE_LONG + RATE_FALSE, W_ENTRY),
    ("canon_fallbacks", RATE_FALLBACK, F_EXACT),
]
E_RARE_FIXED = sum(rate * cost for _, rate, cost in EVENTS)
KM = 64                                      # Markov reserve factor: P[rare work > KM * E_RARE] <= 1/KM
# The coincidence event's worst case is the remaining trail work, TRAIL_MAX (C_COMMON + RESERVE), and RESERVE = KM E_RARE.
# Solving E = E_FIXED + RATE_COINC TRAIL_MAX (C_COMMON + KM E) for E:
E_RARE = (E_RARE_FIXED + RATE_COINC * TRAIL_MAX * C_COMMON) / (1 - KM * RATE_COINC * TRAIL_MAX)
E_RARE_COINC = E_RARE - E_RARE_FIXED
RESERVE = KM * E_RARE
PER_STEP = C_COMMON + RESERVE                # charged instructions per walk step
step_units = PER_STEP / C
SCALAR_MUL = 2 * 384 * F_MAX   # double-and-add over a 256-bit scalar, generous: 768 ops
DP_MAX = 2 * S_max // 2 ** THETA_BITS + 2 * K
DP_COST = 2 ** 20                  # hash-table insert/lookup, transfer and bookkeeping per DP
REPLAY_OPS = 2 ** 13               # unbatched operations per live trail step, replay included: at most 65 replay steps x 70 ops = 4550 <= 2^13 (proof.md section 1.3)
START = 2 * SCALAR_MUL + 2 ** 14   # one start point [a]P + [b]Q from fresh coins

led = Ledger(C)
led.add("walk_steps", S_max * step_units)
# the adder table (independent random points), each with two scalar multiplications; the escape is a doubling, no table
led.add_instructions("adder_table", ADDERS * (2 * SCALAR_MUL + 2 ** 14), preprocessing=True)
led.add_instructions("initial_walk_starts", K * START, preprocessing=True)
# a new trail after each distinguished point (at most DP_MAX) and after each abandonment (at most K)
led.add_instructions("trail_restarts", (DP_MAX + K) * START)
led.add_instructions("distinguished_points", DP_MAX * DP_COST)
# one key match is resolved: both trails are replayed from their coins with coefficients
led.add_instructions("collision_replay", 2 * TRAIL_MAX * REPLAY_OPS * (F_MAX + OVERHEAD))
led.add_instructions("solve_verify_output", 2 * SCALAR_MUL + 2 ** 24)
led.add_instructions("input_validation", 2 ** 24)  # on-curve check; cofactor 1

# Lemma T' (proof.md section 5): abandonment of a trail, first-moment bound on closures. n = 64 (CAP_PERIODS + 1)
# steps before abandonment, which is TRAIL_MAX. Closure probability per step p_c, c = 2^16 (A = 2^16).
CAP_PERIODS = 2 ** THETA_BITS
n_ABANDON = 64 * (CAP_PERIODS + 1)
assert n_ABANDON == TRAIL_MAX
P_CLOSE = RATE_TWO + RATE_LONG + RATE_FALSE              # p_c: bound on the conditional closure probability per step
C_LEMMA_T = 2 ** 16
K_T = n_ABANDON // C_LEMMA_T                             # k = floor(n / c) closures
assert math.e * n_ABANDON * float(P_CLOSE) / K_T <= 0.5  # first moment (e n p_c / k)^k <= 2^-k
assert Fraction(128, C_LEMMA_T) <= Fraction(1, 2 ** 7)
TERM_CLOSURES = 2.0 ** (-K_T)                            # Pr[C_n >= k] <= (e n p_c / k)^k <= 2^-k (0.0 in float)
TERM_FRESH = math.exp(-64 * (1 - 2 ** -7))               # (1 - theta)^(n - 128 k) <= exp(-64 (1 - 2^-7))
P_ABANDON = TERM_CLOSURES + TERM_FRESH
K_TRAILS = DP_MAX + 2 * K                                # trails started: K initial, DP_MAX restarts, K restarts after abandonment
# Within-trail coincidences (proof.md section 3, Lemma G with degenerate pairs and the table term). This bounds
# every re-entry into an escaped cycle (Lemma L), and every within-trail repeat of a class that is not a formal closure.
DELTA_LOOP_F = (Fraction(K_TRAILS) * Fraction(TRAIL_MAX ** 2, 2) * GAMMA
                * (Fraction(2, r) + Fraction(1, r - GAMMA * TRAIL_MAX ** 2 // 2))   # v3: |Gamma| t(t-1)/2 roots
                + Fraction(ADDERS ** 2 * GAMMA, r))
DELTA_LOOP = float(DELTA_LOOP_F)
# Replay cut-off (proof.md section 1.3 step 7): a cycle of length >= 65 is the only way a replay can diverge from the
# live trail through the anchor schedule, and such a cycle is a within-trail repeat. DELTA_CUT bounds
# Pr[a trail has a cycle of length >= 65]: the within-trail bound plus the structural term (Lemma C, lengths >= 65,
# at most 2^-230 per step, summed over S_max steps, at most 2^-100). A cut-off replay fails the run, so DELTA_CUT
# replaces DELTA_LOOP in the failure budget (it contains it).
DELTA_STRUCT_LONG = 2.0 ** -100
DELTA_CUT = DELTA_LOOP + DELTA_STRUCT_LONG
# Lemma T' holds per trail on the trail's own coincidence-free event; the complement adds at most DELTA_LOOP in total.
E_ABANDON = float(K_TRAILS) * P_ABANDON + DELTA_CUT      # expected abandoned trails (coincidence and cut-off correction)
DELTA_ABANDON = E_ABANDON / float(K)                     # Markov: P[more than K abandonments] <= E / K
# D1 (proof.md section 2.3): escape depth below K0 = 2^50. An escape is a closure, so the number of escapes of a
# trail of n = TRAIL_MAX steps is dominated by Bin(n, p_c) (first moment): Pr[escapes >= K0] <= (e n p_c / K0)^K0.
# The union over all trails started gives DELTA_DEPTH. On the complement, every escape depth k is below K0, and the
# exact certificate of evidence/c-ord.json (BSGS, r8/bsgs_c_ord.c) shows that no k with 1 <= k < 2^50 has 2^k in Gamma.
K0 = 2 ** 50
DEPTH_RATIO = math.e * TRAIL_MAX * float(P_CLOSE) / K0
assert DEPTH_RATIO <= 0.5
DELTA_DEPTH_LOG2 = math.log2(K_TRAILS) + K0 * math.log2(DEPTH_RATIO)   # log2 of K_TRAILS * ratio^K0
DELTA_DEPTH = 2.0 ** DELTA_DEPTH_LOG2                                   # 0.0 in double precision
_CERT_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "evidence", "c-ord.json")
with open(_CERT_PATH) as _f:
    _CERT = json.load(_f)
assert _CERT["result"]["k_range"] == "1 <= k < 2^50", "certificate range"
assert _CERT["result"]["matches_in_k_range"] == 0, "some k < 2^50 has 2^k in Gamma"
assert _CERT["result"]["ord_r_2_at_least_m"] is True

tau = Fraction(T * T, 2 * N)
p_model = 1 - math.exp(-float(tau * (1 - eps)))
p_claim = p_model - float(delta) - DELTA_ABANDON - DELTA_CUT - DELTA_DEPTH - 1 / KM
assert p_claim >= 0.39

