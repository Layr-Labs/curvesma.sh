"""Exact accounting for the claim in proof.md (stdlib only; prints JSON).

All work is converted to target-group-operation equivalents. The walk does not use the
6M reference operation: every scalar AArch64 instruction of the attack, including all
field arithmetic (secp_field.h, secp_sub.h), is charged at 1/C, C=1000. Integers and rationals are exact; logarithms are rounded
up to 6 decimals.
"""
import json
import math
from fractions import Fraction

from cscore.exact import Ledger, iroot_ceil, log2, log2_up

r = 0xfffffffffffffffffffffffffffffffebaaedce6af48a03bbfd25e8cd0364141
C = 1000
ADDERS = 2 ** 16             # r-adding walk; index = bits 1..16 of the class key
K = 2 ** 32                  # walks (2^16 processors x 2^16-walk batches)
THETA_BITS = 60              # distinguished-point probability 2^-60
# A trail ends at its first distinguished point. A trail that crosses more than 2^60 anchor
# boundaries (64 steps apart) without one is abandoned, so every trail has fewer than
# TRAIL_MAX steps.
CAP = 64 * 2 ** THETA_BITS
TRAIL_MAX = CAP + 64

# Classes: N nonzero order-6 classes, plus one for the identity (never reached by a walk).
N = (r - 1) // 6 + 1

# Success model (proof.md section 2): 1 - exp(-tau*(1-eps)) - delta with tau = T^2/(2N).
# 2-cycles at most 1/A (Lemma C gives 1/(6 A)), 3..64-cycles at most 3/A^2 (Lemma C).
eps = Fraction(4, ADDERS) + 2 * Fraction(3, ADDERS) + 2 * Fraction(3 * 192, ADDERS ** 2)
delta = Fraction(1, 2 ** 20)
TAU_TARGET = Fraction(5303, 10000)
T_min = iroot_ceil(math.ceil(2 * N * TAU_TARGET), 2)
L = -(-T_min // K)                 # steps per walk counted towards the collision budget
T = K * L
S_max = K * (L + TRAIL_MAX)        # worst case: after L steps each walk finishes its current trail

# Measured average instructions per walk step, everything included (5M + 1S in the kernel's own
# 4x64 assembly, subtractions, fraction approximations and k decision, selection, filters,
# batch bookkeeping, trail restarts and cap, one inversion per 2^16 walks): 778.659 and
# 778.675 on two independent input sets (evidence/measurement/). 795 is charged; the margin
# also covers rare paths (proof.md section 3).
PER_STEP = 795
step_units = Fraction(PER_STEP, C)

# One unbatched step (affine add/double with its own Fermat inversion, adder selection
# and bookkeeping): measured 22,913.1 and 22,914.0 instructions; 2^15 is charged.
UNBATCHED = 2 ** 15
SCALAR_MUL = 2 * 384 * UNBATCHED   # double-and-add over a 256-bit scalar, generous: 768 ops
DP_MAX = 2 * S_max // 2 ** THETA_BITS + 2 * K
DP_COST = 2 ** 20                  # hash-table insert/lookup, transfer and bookkeeping per DP
REPLAY_OPS = 2 ** 12               # unbatched operations per live trail step, replay included (proof.md section 1.3)
START = 2 * SCALAR_MUL + 2 ** 14   # one start point [a]P + [b]Q from fresh coins

led = Ledger(C)
led.add("walk_steps", S_max * step_units)
led.add_instructions("adder_table", ADDERS * (2 * SCALAR_MUL + 2 ** 14), preprocessing=True)
led.add_instructions("initial_walk_starts", K * START, preprocessing=True)
# a new trail after each distinguished point (at most DP_MAX) and after each abandonment (at most K)
led.add_instructions("trail_restarts", (DP_MAX + K) * START)
led.add_instructions("distinguished_points", DP_MAX * DP_COST)
# one key match is resolved: both trails are replayed from their coins with coefficients
led.add_instructions("collision_replay", 2 * TRAIL_MAX * REPLAY_OPS * (UNBATCHED + 2 ** 10))
led.add_instructions("solve_verify_output", 2 * SCALAR_MUL + 2 ** 24)
led.add_instructions("input_validation", 2 ** 24)  # on-curve check; cofactor 1

tau = Fraction(T * T, 2 * N)
p_model = 1 - math.exp(-float(tau * (1 - eps)))
p_claim = p_model - float(delta)
assert p_claim >= 0.39

# Total-work cutoff (proof.md section 1.3 step 8, section 3). Each of PROCS processors may
# spend at most (S_max / PROCS) * PER_STEP instructions on walk steps, minus a reserve of one
# batch step, and stops there. Per-step costs X lie in [0, M]; under H1' each step's expected
# cost given the past is at most MEAN = measured average + rare-event allowance (Lemma C
# rates). Azuma-Hoeffding: P[a processor needs more] <= exp(-2 (n t - R)^2 / (n M^2)).
PROCS = 2 ** 16
BATCH = 2 ** 16
METER_READ = 2 ** 14                     # one retired-instruction counter read (system call), charged
MEAN_MEASURED = Fraction("778.675")             # larger of the two measured averages
G = 6                                    # class size
RARE = (Fraction(2, G * ADDERS) * 2 * UNBATCHED          # 2-cycle confirmation and escape
        + Fraction(3, ADDERS ** 2) * 68 * UNBATCHED      # 3..64-cycle look-ahead and escape
        + Fraction(2, 2 ** 64) * 68 * UNBATCHED          # false 64-bit filter matches
        + Fraction(1, 2 ** 55) * 2 ** 10                 # exact-k fallbacks (order 6 only)
        + Fraction(METER_READ, 64 * BATCH))              # the work meter, read every 64 batch steps
# Most one walk step can cost: the kernel's batch_step is 2786 instructions with no loop on the
# common path (< 2^12), plus the batch inversion that one step of each batch carries
# (< 2 ** 15), plus the rare paths: a 65-step look-ahead and an escape (68 unbatched operations).
M = 2 ** 12 + 2 ** 15 + 68 * UNBATCHED
n_proc = S_max // PROCS
assert n_proc * PROCS == S_max
t = Fraction(PER_STEP) - MEAN_MEASURED - RARE
R = 64 * BATCH * M                       # overshoot reserve: up to 64 batch steps between meter reads
expo = 2 * (n_proc * t - R) ** 2 / (n_proc * M * M)
expo_log2 = log2(int(expo))
assert t > 0 and expo_log2 > 40

