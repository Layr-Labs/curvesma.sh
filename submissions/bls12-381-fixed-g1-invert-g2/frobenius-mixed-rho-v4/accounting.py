def v_rate(s):
    """Collision rate for square fraction s: 1 - s^2 - (1 - s) / r_a (see walk-spec section 7)."""
    return 1 - s * s - (1 - s) / R_A


def union_log2(ell, s):
    """log2 of the union bound on the probability that a window of ell consecutive steps is a formal
    cancellation: all steps additive, and the rotation multiset of each adder decomposes into 2-gons and 3-gons
    (walk-spec section 9.5, Proposition G). Sum over partitions of ell positions into a 2-blocks and b 3-blocks:
        (1 - s)^ell * sum_{2a + 3b = ell} ell! / (2^a a! 6^b b!) * 2^b * 6792^(-(a + 2b)).
    """
    terms = []
    for b in range(ell // 3 + 1):
        if (ell - 3 * b) % 2:
            continue
        a = (ell - 3 * b) // 2
        lt = (math.lgamma(ell + 1) - (a * math.log(2) + math.lgamma(a + 1)) - (b * math.log(6) + math.lgamma(b + 1))
              + b * math.log(2) - (a + 2 * b) * math.log(ADDITIVE_CELLS))
        terms.append(lt / math.log(2))
    mx = max(terms)
    return ell * math.log2(1 - float(s)) + mx + math.log2(sum(2 ** (t - mx) for t in terms))


def event_rate_bound(s):
    """Unconditional upper bound on the probability per main step that a closure event starts (a first revisit of
    a window state, lengths 2 to 64): the 2-cycle term (1 - s)/(12 r_a) (the first step additive, the return step
    with the same adder and rotation +6), the formal union over lengths 3 to 64, and the non-formal closures
    (12 * 64 / r). The 2-cycle term is the measured rate (ratio 1.0021 at S = 458)."""
    two = (1 - float(s)) / (12 * R_A)
    formal = sum(2 ** union_log2(ell, s) for ell in range(3, 65))
    nonformal = 12 * 64 / R
    return two + formal + nonformal


def trap_bound(s):
    """Per-step probability that an undetected cycle (length 65 to CAP) closes: (a) formal windows of lengths 65..400
    (union bound) and all-additive windows longer than 400, (1 - s)^401 / s; (b) non-formal closures, probability
    1/r per candidate (heuristic H5) over 12 CAP candidates. The trap term also covers the revisit steps of an
    undetected cycle, which are at most the trail cap per trap."""
    union = sum(2 ** union_log2(ell, s) for ell in range(65, 401))
    additive_tail = float(1 - s) ** 401 / float(s)
    nonformal = 12 * CAP / R
    per_step = union + additive_tail + nonformal
    return {"union_65_400": union, "additive_tail_401": additive_tail, "nonformal_per_step": nonformal,
            "per_step": per_step}


def fresh_steps_needed(V, delta, f):
    """Fresh steps T with 1 - exp(-f tau) - delta >= TARGET, tau = T^2 V / (2N)."""
    tau = -math.log(1 - float(TARGET) - delta) / f
    return math.ceil(math.sqrt(2 * N * tau / float(V)) * (1 + 1e-12))


def cap_loss(c):
    """Fraction of collisions lost to the trail cap: 2 (1 + c) e^(-c)."""
    return 2 * (1 + c) * math.exp(-c)


def log2_chernoff(mu, eps):
    """log2 of exp(-eps^2 mu / 3): the multiplicative Chernoff tail for a count with mean mu."""
    return -(float(eps) ** 2) * mu / 3 / math.log(2)


def dp_capacity(M):
    """Records of the table (walk-spec section 9.4): records <= X + J with X the fresh DP flags (mean mu = M 2^-60,
    dominated by a binomial; overflow at 2 mu has probability at most exp(-mu/3)) and J the joins (at most J_MAX,
    Markov with failure E[J]/J_MAX, E[J] <= M^2/N). D = ceil(2 mu) + J_MAX."""
    mu = Fraction(M, 2 ** DP_BITS)
    return math.ceil(2 * mu) + J_MAX


def bucket_failure_log2(D):
    """log2 of the probability that some bucket receives more records than its capacity 2^BUCKET_LOG2 (Chernoff per
    bucket on the binomial occupancy with mean D / 2^B_BITS, union over the buckets)."""
    mu_b = D / 2 ** B_BITS
    cap = 2 ** BUCKET_LOG2
    if cap <= mu_b:
        return 0.0
    delta_b = cap / mu_b - 1
    per_bucket = -(delta_b ** 2) * mu_b / 3 / math.log(2) if delta_b < 1 else -(delta_b * mu_b) / 3 / math.log(2)
    return B_BITS + per_bucket


def bitonic_comparators(n):
    """Compare-exchanges of the bitonic network on n = 2^k slots: n k (k + 1) / 4."""
    k = n.bit_length() - 1
    assert n == 1 << k
    return n * k * (k + 1) // 4


