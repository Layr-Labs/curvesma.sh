"""Collection region F_Vor: a in F_Vor iff T2(u a) >= T2(a) for the 10 listed units u. With X_k = |sigma_k(a)|^2 at the
four complex places (k = 1, 7, 4, 2), T2(u a) - T2(a) = sum_k (|sigma_k(u)|^2 - 1) X_k is linear in X, so F_Vor is the
polyhedral cone C = {X >= 0 : sum_k (f_k(u) - 1) X_k >= 0 for the 10 units}.

check(units) proves, up to float tolerance, that every non-torsion unit u of the lattice generated by the 10 units
satisfies sum_k (f_k(u) - 1) X_k >= 0 on C, so a in F_Vor is T2-minimal in its orbit under that group and F_Vor / mu_30
holds one point per orbit (ties are a measure-zero boundary broken by the canonical order):
  1. extreme rays of C (normalised sum X = 1): every feasible intersection of 3 of the 14 constraints as equalities;
  2. m0 = min over rays of min_k X_k > 0 (every ray strictly positive);
  3. a unit with lam_max = max_k log|sigma_k(u)| > log(1/m0)/2 gives sum_k f_k X_k >= e^(2 lam_max) m0 > 1 = sum X on
     every ray, so only units with lam_max <= log(1/m0)/2 can fail; they are enumerated exactly in the log lattice
     (integer combinations of a basis of 3 listed units, bounded by the inverse basis);
  4. each enumerated non-torsion unit is checked on every ray.
small_units() lists all units with coefficients in {-1, 0, 1}^8 and checks they lie in the generated lattice."""
import cmath, itertools, math

PL = [cmath.exp(2j * math.pi * k / 15) for k in (1, 7, 4, 2)]


def logs(u):
    return [math.log(abs(sum(c * z ** j for j, c in enumerate(u)))) for z in PL]


def _solve3(A, b):
    # 3x3 linear system, Cramer's rule in floats
    d = lambda M: (M[0][0] * (M[1][1] * M[2][2] - M[1][2] * M[2][1]) - M[0][1] * (M[1][0] * M[2][2] - M[1][2] * M[2][0])
                   + M[0][2] * (M[1][0] * M[2][1] - M[1][1] * M[2][0]))
    D = d(A)
    if abs(D) < 1e-12:
        return None
    out = []
    for i in range(3):
        M = [row[:] for row in A]
        for r in range(3):
            M[r][i] = b[r]
        out.append(d(M) / D)
    return out


def rays(units):
    cons = [[math.exp(2 * l) - 1.0 for l in logs(u)] for u in units] + [[float(i == k) for k in range(4)] for i in range(4)]
    out = []
    for tri in itertools.combinations(range(len(cons)), 3):
        # X_3 = 1 - X_0 - X_1 - X_2 (normalisation); tight constraints c.X = 0
        A = []; b = []
        for t in tri:
            c = cons[t]; A.append([c[0] - c[3], c[1] - c[3], c[2] - c[3]]); b.append(-c[3])
        s = _solve3(A, b)
        if s is None:
            continue
        X = s + [1.0 - sum(s)]
        if all(sum(c[k] * X[k] for k in range(4)) >= -1e-9 for c in cons):
            if not any(max(abs(x - y) for x, y in zip(X, Y)) < 1e-9 for Y in out):
                out.append(X)
    return out


def check(units, mul):
    R = rays(units)
    m0 = min(min(X) for X in R)
    assert R and m0 > 0
    lam_bound = math.log(1.0 / m0) / 2.0
    L = [logs(u) for u in units]
    basis = None
    for tri in itertools.combinations(range(len(units)), 3):
        M = [L[i][:3] for i in tri]
        if _solve3(M, [1.0, 0.0, 0.0]) is not None:
            basis = tri; break
    B = [L[i] for i in basis]
    # every listed unit is an integer combination of the basis (same lattice)
    BT = [[B[r][c] for r in range(3)] for c in range(3)]
    for l in L:
        co = _solve3(BT, l[:3]); assert co is not None and all(abs(x - round(x)) < 1e-6 for x in co)
    # bound on integer coordinates for lam_max <= lam_bound: |lam_k| <= 3 lam_bound (sum lam = 0)
    lim = 3.0 * lam_bound
    inv_rows = [_solve3(BT, [float(i == r) for r in range(3)]) for i in range(3)]
    cmax = [math.ceil(lim * sum(abs(inv_rows[i][r]) for i in range(3))) + 1 for r in range(3)]
    tested = 0
    for a in range(-cmax[0], cmax[0] + 1):
        for b in range(-cmax[1], cmax[1] + 1):
            for c in range(-cmax[2], cmax[2] + 1):
                if a == b == c == 0:
                    continue
                lam = [a * B[0][k] + b * B[1][k] + c * B[2][k] for k in range(4)]
                if max(lam) > lam_bound:
                    continue
                tested += 1
                f = [math.exp(2 * x) for x in lam]
                assert all(sum((f[k] - 1.0) * X[k] for k in range(4)) >= -1e-9 for X in R), (a, b, c)
    return dict(rays=len(R), min_ray_coord=round(m0, 6), lam_bound=round(lam_bound, 4), units_tested=tested,
                basis=list(basis))


def small_units(units, norm):
    L = [logs(u) for u in units]
    basis = None
    for tri in itertools.combinations(range(len(units)), 3):
        if _solve3([L[i][:3] for i in tri], [1.0, 0.0, 0.0]) is not None:
            basis = tri; break
    BT = [[L[basis[r]][c] for r in range(3)] for c in range(3)]
    n = 0
    for v in itertools.product((-1, 0, 1), repeat=8):
        if any(v) and abs(norm(list(v))) == 1:
            co = _solve3(BT, logs(list(v))[:3]); assert co is not None and all(abs(x - round(x)) < 1e-6 for x in co)
            n += 1
    return n


def full_group(units, y_pow, sub, add, norm):
    """Sinnott: for n = 15 (two primes, b = 0) and h+(Q(zeta_15)) = 1 the cyclotomic units C equal the full unit group E
    (up to torsion). C is generated by 1 - y^a (gcd(a, 15) = 1) and 1 + y^3 (= (1 - zeta_5^2)/(1 - zeta_5)) with torsion.
    Each generator lies in the lattice L of the 10 units, so C <= L <= E = C and L = E."""
    L = [logs(u) for u in units]
    basis = None
    for tri in itertools.combinations(range(len(units)), 3):
        if _solve3([L[i][:3] for i in tri], [1.0, 0.0, 0.0]) is not None:
            basis = tri; break
    BT = [[L[basis[r]][c] for r in range(3)] for c in range(3)]
    one = [1] + [0] * 7
    gens = [sub(one, y_pow(a)) for a in (1, 2, 4, 7, 8, 11, 13, 14)] + [add(one, y_pow(3))]
    for g in gens:
        assert abs(norm(g)) == 1
        co = _solve3(BT, logs(g)[:3]); assert co is not None and all(abs(x - round(x)) < 1e-6 for x in co)
    return len(gens)
