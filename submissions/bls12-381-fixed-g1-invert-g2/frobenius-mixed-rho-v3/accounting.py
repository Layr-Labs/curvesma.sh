"""Frobenius-class mixed rho on GT for the bls12-381 fixed-argument pairing tracks, with cscore.exact.

Work is in target-group-operation units: one dense Fp12 multiplication costs 1, and other
scalar AArch64 instructions cost (instructions / C) with C = 20,000 (COST_MODEL.md). The walk
is specified in work-gt/SPEC-gt-walk.md. The procedure stops when its work counter reaches
W_MAX; the score is log2(W_MAX). Every term of W_MAX is a bound on the work of the first M main
steps (see charge_bound), so that the procedure executes at least M main steps before the
cutoff with the failure probability computed in build().
"""
import json
import math
from fractions import Fraction

from cscore import exact

R = 0x73eda753299d7d483339d80809a1d80553bda402fffe5bfeffffffff00000001
N = (R - 1) // 12
C = 20000
ADDER_BITS = 10
R_A = 1 << ADDER_BITS
DP_BITS = 60
WALKS = 1 << 20
TARGET = Fraction(41, 100)     # claimed success probability
EXP_UNITS = 381                # one exponentiation by a 255-bit scalar: ~255 squarings + ~127 multiplications, all charged 1
FROBENIUS_UNITS = Fraction(7421, C)  # blst_fp12_frobenius_map, measured (research-arith.md)
# Distinguished points: a store and a sort-and-lookup, both measured (step.c, modes 'sortbench' and the
# DP-every-step run). Store: 1479 instructions per record. Sort: one compare and one 80-byte exchange per record
# per level, 48 instructions measured, with at most ceil(log2 D) = 67 levels; overflow check 10 instructions.
DP_STORE_INST = Fraction("1479.0")
SORT_INST_PER_LEVEL = Fraction(48)
SORT_LEVELS = 67
OVERFLOW_INST = Fraction(10)
DP_CHARGE_UNITS = (DP_STORE_INST + SORT_LEVELS * SORT_INST_PER_LEVEL + OVERFLOW_INST) / C
SOLVE_INSTRUCTIONS = 2 ** 29   # final scalar multiplication, verification pairing, input checks
CAP_C = 64                     # trail cap in units of 2^DP_BITS: a walk runs at most 64 * 2^60 steps without a DP
CAP = CAP_C * 2 ** DP_BITS     # 2^66 main steps
WINDOW = 127                   # main steps a detected cycle can run before its anchor check fires (2 * 64 - 1)
EVENT_OPS = 66                 # extra operations per detected cycle: walk-through (<= 64), the check step and the escape
DP_BYTES = 80                  # 16-byte key fingerprint and two 32-byte canonical exponents
DETECTOR_BYTES = 2 * 48 + 2 + 16  # per walk: previous and anchor keys (48 bytes each), two flags, trail age (128-bit)
ELEMENT_BYTES = 576            # one Fp12 element in blst (12 x 48 bytes)
EXPONENT_BYTES = 32
FINGERPRINT_BITS = 128         # key bits 70..197 of the Montgomery integer: they vary (bits 10..69 are zero by the DP test)
ADDITIVE_CELLS = (R_A - 458) * 12   # (adder, rotation) pairs reachable by an additive step: 566 * 12 = 6792
NONADDITIVE = Fraction(458, R_A)     # square branch probability s

# Uninstrumented runs of the production kernel, S = 458, seeds 1 and 2, 2^20 rounds of 64 walks
# each (measurement/native_run.sh, evidence/native-counts.json). Used for consistency checks only.
MEASURED_S = 458
NATIVE_STEPS = 2 * 67108864
NATIVE_CYCLE2 = 2979 + 3071            # detected 2-cycles
NATIVE_CYCLE_LONG = 1                  # detected longer cycles

# Callgrind interval 256 -> 512 rounds at S = 458 with distinguished-point density zero, seeds 1 and 2
# (measurement/RESULT.json). Distinguished-point work is charged separately (DP_INSTRUCTIONS).
# Per-step instruction counts of the kernel's straight-line step, measured with every step of one type
# (step.c has no data-dependent branch on this path; the forced-type runs are add1 and sq1 in the
# package's measurement/forced/, and add1 with DP_BITS = 0 gives the store cost). The adder step includes the
# reference operation (blst_fp12_mul, 22,998 measured; 22,996 in the organizer's measurement, used here so
# that the other work is not underestimated). The square step includes blst_fp12_cyclotomic_sqr.
A_INST = Fraction("26730.2")   # all-adder step: 26,730.16 with 4 cycle events in the run (conservative)
Q_INST = Fraction("13511.44")  # all-square step, no events
REF_INST = Fraction(22996)     # organizer reference: blst_fp12_mul, the unit
ANCHOR_INST = Fraction(20)     # anchor refresh every 64 steps, charged as a copy at every step (upper bound)
KAPPA = Fraction(4902, 10000)  # blst_fp12_cyclotomic_sqr: 9804 instructions, 0.4902
A_UNITS = 1 + (A_INST - REF_INST + ANCHOR_INST) / C
Q_UNITS = (Q_INST + ANCHOR_INST) / C

# Tail parameters for the Chernoff and Markov bounds used in charge_bound().
EPS_SQ = Fraction(1, 10 ** 6)  # relative deviation of the square count (per step)
EPS_EV = Fraction(1, 1000)     # relative slack on the cycle-event count
EPS_DP = 1                     # the distinguished-point count may be twice its mean (DP table capacity)


def v_rate(S):
    """Collision rate for S square slots out of R_A: 1 - s^2 - (R_A - S) / R_A^2 (the R_A - S additive
    adders are each selected with probability 1/R_A; the square branch with probability s)."""
    s = Fraction(S, R_A)
    return 1 - s * s - Fraction(R_A - S, R_A * R_A)


def union_log2(ell, s):
    """log2 of the union bound on the probability that a window of ell consecutive steps is a formal
    cancellation: all steps additive, and the multiset of (adder, rotation) pairs decomposes into 2-gons
    {(h, k), (h, k + 6)} and 3-gons {(h, k), (h, k + 4), (h, k + 8)} for each adder h (Lam-Leung: the
    nonnegative vanishing sums of 12th roots of unity are generated by 2-gons and 3-gons). Per partition of
    the window into gon blocks, each block costs one free first step and its partners: 1/6792 for a 2-gon,
    2/6792^2 for a 3-gon. Sum over partitions of ell labelled positions into a 2-blocks and b 3-blocks:
        (1 - s)^ell * sum_{2a + 3b = ell} ell! / (2^a a! 6^b b!) * 2^b * 6792^(-(a + 2b)).
    """
    terms = []
    for b in range(ell // 3 + 1):
        if (ell - 3 * b) % 2:
            continue
        a = (ell - 3 * b) // 2
        lt = (math.lgamma(ell + 1) - (a * math.log(2) + math.lgamma(a + 1)) - (b * math.log(6) + math.lgamma(b + 1))
              + b * math.log(2) - (a + 2 * b) * math.log(ADDITIVE_CELLS))
        terms.append(lt / math.log(2))
    mx = max(terms)
    return ell * math.log2(1 - float(s)) + mx + math.log2(sum(2 ** (t - mx) for t in terms))


def event_rate_bound(s):
    """Upper bound on the probability per main step that a cycle is detected (any length up to 64):
    the 2-cycle rate (1 - s)/(12 * 1024) for a window that returns to the state two steps back, plus the
    formal windows of length 3 to 64 (union bound), plus the non-formal closures (1 / r per candidate).
    The 2-cycle term is exact under the uniform-choice model; the measured 2-cycle count is 4.5076e-5 per
    step against this 4.4982e-5 term (ratio 1.0021)."""
    two = (1 - float(s)) / (12 * R_A)
    formal = sum(2 ** union_log2(ell, s) for ell in range(3, 65))
    nonformal = 12 * 64 / R
    return two + formal + nonformal


def trap_bound(s):
    """Per-step probability that an undetected cycle (length 65 to CAP) closes. Two parts:
    (a) formal windows (all steps additive, Lam-Leung decomposable): union bound for lengths 65..400
        (union_log2) and, for longer windows, the probability that all steps are additive, (1 - s)^ell,
        which bounds the formal event (the formal event requires no square, see H6 below);
    (b) non-formal closures: a closure whose exponent coefficient is nonzero is an event of probability
        1/r for uniform coins (heuristic H5), over 12 candidates (class powers) per length and per step.
    H6: the square count q has 2^q not a 12th root of unity for q < 2^247, so a window with a square has a
    nonzero coefficient at e_0 and falls under (b). Proven by computing the order of 2 modulo r from the
    factorisation of r - 1 (measurement notes in STATUS.md).
    """
    union = sum(2 ** union_log2(ell, s) for ell in range(65, 401))
    additive_tail = float(1 - s) ** 401 / float(s)
    nonformal = 12 * CAP / R
    per_step = union + additive_tail + nonformal
    return {"union_65_400": union, "additive_tail_401": additive_tail, "nonformal_per_step": nonformal,
            "per_step": per_step}


def fresh_steps_needed(V, delta, f):
    """Fresh steps T with 1 - exp(-f tau) - delta >= TARGET, tau = T^2 V / (2N)."""
    tau = -math.log(1 - float(TARGET) - delta) / f
    return math.ceil(math.sqrt(2 * N * tau / float(V)) * (1 + 1e-12))


def cap_loss(c):
    """Fraction of collisions lost to the trail cap: 2 (1 + c) e^(-c)."""
    return 2 * (1 + c) * math.exp(-c)


def log2_chernoff(mu, eps):
    """log2 of exp(-eps^2 mu / 3): the multiplicative Chernoff tail for a count with mean mu."""
    return -(float(eps) ** 2) * mu / 3 / math.log(2)


def build():
    S = MEASURED_S
    s = Fraction(S, R_A)
    V = v_rate(S)
    f = 1 - cap_loss(CAP_C)
    p_ev = event_rate_bound(s) * (1 + float(EPS_EV))
    assert p_ev <= 4.6e-5, p_ev
    w = WINDOW * p_ev                                   # detected-cycle waste per main step
    lag = WALKS * 2 ** DP_BITS                          # detection lag: each walk runs to its next DP before a collision is seen
    s_low = float(s) - float(EPS_SQ)                    # lower confidence bound on the square fraction
    trap = trap_bound(s)
    delta = 0.0
    for _ in range(4):                                  # the trap term depends on M, M on the trap term
        T = fresh_steps_needed(V, delta, f)
        M = math.ceil((T + lag) / (1 - w))
        delta_trap = M * trap["per_step"]
        delta = delta_trap + 2 ** -60                   # plus the fingerprint Markov bound (below)
    # Per-step charge for the operation mix: adders cost 1, squares kappa; the square count is at least
    # (s - EPS_SQ) M with probability >= 1 - exp(-2 EPS_SQ^2 M), so the charge uses s_low.
    s_low_f = Fraction(s_low).limit_denominator(10 ** 12)
    step_charge = (1 - s_low_f) * A_UNITS + s_low_f * Q_UNITS
    event_charge = Fraction(p_ev).limit_denominator(10 ** 12) * EVENT_OPS * A_UNITS
    D = 2 * M // 2 ** DP_BITS + 2 * WALKS               # distinguished-point capacity (also the charged count)
    mu_pairs = Fraction(D * D, 2 ** (FINGERPRINT_BITS + 1))
    fp_threshold = 2 ** 60                              # Markov: P(pairs >= threshold * mean) <= 1 / threshold
    components = {
        "walk_steps": M * step_charge,
        "detected_cycles": M * event_charge,
        "adder_table": R_A * (2 * EXP_UNITS + 12 * FROBENIUS_UNITS),
        # One restart per distinguished point covers the trail-cap restarts (at most M / CAP + WALKS of them).
        "walk_starts_and_restarts": (WALKS + D) * 2 * EXP_UNITS,
        "distinguished_points": D * DP_CHARGE_UNITS,
        "fingerprint_verification": fp_threshold * mu_pairs * EXP_UNITS,
        "solve_verify_output": Fraction(SOLVE_INSTRUCTIONS, C),
    }
    W_max = sum(components.values())

    # Failure terms of the success bound and of the work and capacity bounds (log2).
    mu_dp = M / 2 ** DP_BITS
    # Every failure term kept (probabilities over the first M main steps and the whole run).
    # Square count: Hoeffding on i.i.d. adder/square choices (H7).
    # Detected cycles of length <= 64: each is a function of a window of at most 64 consecutive i.i.d. choices,
    # so the indicators split into 64 interleaved subsequences of independent indicators; Chernoff on each
    # subsequence (mean p M / 64), union over the 64 subsequences.
    # Non-formal detections of length <= 64 (exponent relation, 1/r per candidate): Markov on the expectation.
    # Distinguished points: Chernoff on the i.i.d. tests (capacity overflow stops the procedure).
    # Fingerprint matches are metered when they occur; Markov bounds the metered count (2^60 times the mean).
    failures = {
        "trap_formal_and_nonformal": delta_trap,
        "fingerprint_markov": 2.0 ** -60,
        "square_count_hoeffding": 2.0 ** (-2 * float(EPS_SQ) ** 2 * M / math.log(2)),
        "cycle_count_blocking_log2": math.log2(64) + log2_chernoff(p_ev * M / 64, EPS_EV),
        "nonformal_short_expectation": 12 * 64 * M / R,
        "dp_count_overflow_log2": log2_chernoff(mu_dp, Fraction(1, 1)),
    }
    delta_total = (failures["trap_formal_and_nonformal"] + failures["fingerprint_markov"]
                   + failures["square_count_hoeffding"] + 2.0 ** failures["cycle_count_blocking_log2"]
                   + failures["nonformal_short_expectation"] + 2.0 ** failures["dp_count_overflow_log2"])
    tau_eff = float(T) ** 2 * float(V) / (2 * float(N))
    success_model = 1 - math.exp(-f * tau_eff)
    success_lower = success_model - delta_total
    success_uncharged = 1 - math.exp(-f * tau_eff * (1 - w) ** 2) - delta_total

    score = exact.log2_up(W_max)
    peak_bytes = (D * DP_BYTES + 12 * R_A * (ELEMENT_BYTES + 2 * EXPONENT_BYTES)
                  + WALKS * (2 * ELEMENT_BYTES + 2 * EXPONENT_BYTES + DETECTOR_BYTES))
    report = {
        "components_log2_units": {k: round(exact.log2(v), 6) for k, v in components.items()},
        "time_log2": str(score),
        "time_log2_decimal": float(score),
        "time_log2_float": exact.log2(W_max),
        "score_rational": {"numerator": str(score.numerator), "denominator": str(score.denominator)},
        "preprocessing_log2": str(exact.log2_up(components["adder_table"] + components["walk_starts_and_restarts"])),
        "parameters": {
            "N_log2": round(math.log2(N), 6), "square_slots": S, "r_a": R_A, "s": float(s),
            "V": float(V), "walk_steps_T_log2": round(math.log2(T), 6),
            "main_steps_log2": round(math.log2(M), 6), "lag_steps_log2": round(math.log2(lag), 6),
            "distinguished_points_log2": round(math.log2(D), 6), "dp_bits": DP_BITS, "walks": WALKS,
            "square_fraction_lower": s_low, "step_charge": float(step_charge), "event_charge": float(event_charge),
            "event_rate_bound": p_ev, "window": WINDOW, "wasted_fraction_charged": w,
            "trail_cap_log2_steps": round(math.log2(CAP), 6), "detection_factor": f,
            "fingerprint_bits": FINGERPRINT_BITS, "false_pairs_mean_log2": round(math.log2(float(mu_pairs)), 6),
            "dp_capacity_records": D, "dp_capacity_log2": round(math.log2(D), 6),
        },
        "trap_bound": trap,
        "failure_terms": failures,
        "delta_total": delta_total,
        "memory_log2_bytes": str(exact.log2_up(max(1, peak_bytes))),
        "success": {"tau_eff": tau_eff, "eps": float(1 - V), "model": success_model,
                    "delta": delta_total, "lower_bound": success_lower},
        "success_if_waste_not_charged": success_uncharged,
        "a_units": float(A_UNITS), "q_units": float(Q_UNITS), "dp_charge_units": float(DP_CHARGE_UNITS), "kappa": float(KAPPA),
    }
    return report


