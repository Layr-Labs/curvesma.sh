"""Frobenius-class mixed rho on GT for the bls12-381 fixed-argument pairing tracks, with cscore.exact.

Work is in target-group-operation units: one dense Fp12 multiplication costs 1, and other
scalar AArch64 instructions cost (instructions / C) with C = 20,000 (COST_MODEL.md). The walk
is specified in work-gt/SPEC-gt-walk.md. Its per-step costs come from the production kernel
(measurement/ in the package) at the production square count S = 458, and its cycle rate
from uninstrumented runs of the same kernel. Both pairing tracks share this computation; the
wrapper scalar multiplication differs only in the group and is charged the same bound.
"""
import json
import math
from fractions import Fraction

from cscore import exact

R = 0x73eda753299d7d483339d80809a1d80553bda402fffe5bfeffffffff00000001
C = 20000
ADDER_BITS = 10
R_A = 1 << ADDER_BITS
DP_BITS = 60
WALKS = 1 << 20
CAP = 64 * 2 ** DP_BITS
TARGET = Fraction(41, 100)
DELTA = Fraction(1, 2 ** 20)
DP_INSTRUCTIONS = 2 ** 20
EXP_UNITS = 381              # one exponentiation by a 255-bit scalar: ~255 squarings + ~127 multiplications, all charged 1
FROBENIUS_UNITS = Fraction(7421, C)  # blst_fp12_frobenius_map, measured (research-arith.md)
ANCHOR_PERIOD = 64
WINDOW = 2 * ANCHOR_PERIOD - 1       # main steps a cycle can run before its anchor check fires (127)
DP_BYTES = 80                # 16-byte key fingerprint and two 32-byte exponents
DETECTOR_BYTES = 2 * 48 + 2  # per walk: previous key and anchor key (Fp, 48 bytes each), two valid flags
ELEMENT_BYTES = 576          # one Fp12 element in blst (12 x 48 bytes)
EXPONENT_BYTES = 32
Z_UPPER = 1.6449            # one-sided 95% normal quantile for the Poisson upper bound

# Uninstrumented runs of the production kernel, S = 458, seeds 1 and 2, 2^20 rounds of 64 walks
# each (measurement/native_run.sh, evidence/native-counts.json).
MEASURED_S = 458                       # square slots out of R_A: s = 0.447265625
NATIVE_STEPS = 2 * 67108864
NATIVE_ADDS = 37092453 + 37096088      # group operations that are adder multiplications
NATIVE_SQRS = 30022369 + 30018923      # squarings, including escapes
NATIVE_CYCLE_EVENTS = 2979 + 3071 + 1  # 2-cycle and longer-cycle detections (cyc2 + cycl)

# Callgrind interval 256 -> 512 rounds, seeds 1 and 2, distinguished-point density zero (measurement/RESULT.json).
C2 = Fraction(1445, 10000)     # other work per main step, distinguished-point work excluded: 0.144301 and 0.144287; max with a 0.1% margin, rounded up
KAPPA = Fraction(4902, 10000)  # blst_fp12_cyclotomic_sqr: 9804 instructions, 0.4902


def v_rate(S):
    """Collision rate for S square slots out of R_A: 1 - s^2 - (R_A - S) / R_A^2 (the R_A - S additive
    adders are each selected with probability 1/R_A; the square branch with probability s)."""
    s = Fraction(S, R_A)
    return 1 - s * s - Fraction(R_A - S, R_A * R_A)


def choose_square_slots(c2, kappa):
    """Square-slot count S of R_A minimising (cost per step) / sqrt(V)."""
    best = None
    for S in range(R_A):
        s = S / R_A
        f = ((1 - s) + s * float(kappa) + float(c2)) / math.sqrt(float(v_rate(S)))
        if best is None or f < best[0]:
            best = (f, S)
    return best[1]


def walk_count(N, V):
    """Smallest T with 1 - exp(-T^2 V / (2N)) - DELTA >= TARGET (random-mapping model)."""
    tau = -math.log(1 - float(TARGET) - float(DELTA))
    T = math.sqrt(2 * N * tau / float(V))
    return math.ceil(T * (1 + 1e-9))


def poisson_upper_rate(k, n):
    """One-sided 95% upper bound on a Poisson rate from k events in n steps (normal approximation)."""
    return Fraction((k + 1) + Z_UPPER * math.sqrt(k + 1)).limit_denominator(10 ** 6) / n


def build():
    N = (R - 1) // 12
    S = MEASURED_S  # the kernel is measured at this count; choose_square_slots(C2, KAPPA) is 456, about 2e-6 relative away
    s = Fraction(S, R_A)
    V = v_rate(S)
    T = walk_count(N, V)                       # fresh steps: the model's T
    # The cycle detector wastes at most WINDOW main steps per detected cycle; the rate is the
    # measured upper bound. Total main steps = T / (1 - waste), plus one trail of 2^DP_BITS steps per walk.
    rate = poisson_upper_rate(NATIVE_CYCLE_EVENTS, NATIVE_STEPS)
    waste = WINDOW * rate
    total_steps = math.ceil(T / float(1 - waste)) + WALKS * 2 ** DP_BITS
    trails = total_steps // 2 ** DP_BITS + 1
    dps = 2 * total_steps // 2 ** DP_BITS + 2 * WALKS
    adds_per_step = Fraction(NATIVE_ADDS, NATIVE_STEPS)
    sqrs_per_step = Fraction(NATIVE_SQRS, NATIVE_STEPS)
    step_units = adds_per_step + sqrs_per_step * KAPPA + C2

    led = exact.Ledger(C)
    led.add("walk_steps", total_steps * step_units)
    led.add("adder_table", R_A * (2 * EXP_UNITS + 12 * FROBENIUS_UNITS), preprocessing=True)
    led.add("walk_starts_and_restarts", (WALKS + trails) * 2 * EXP_UNITS, preprocessing=True)
    led.add_instructions("distinguished_points", dps * DP_INSTRUCTIONS)
    led.add("collision_replay", 2 * CAP * (1 + C2))
    # Two distinct distinguished points with equal 128-bit fingerprints are verified by one
    # exponentiation each: expected count dps^2 / 2^129.
    led.add("fingerprint_verification", Fraction(dps * dps, 2 ** 129) * EXP_UNITS)
    led.add_instructions("solve_verify_output", 2 ** 29)  # scalar multiplication, verification pairing, input checks

    peak_bytes = (dps * DP_BYTES + 12 * R_A * (ELEMENT_BYTES + 2 * EXPONENT_BYTES)
                  + WALKS * (2 * ELEMENT_BYTES + 2 * EXPONENT_BYTES + DETECTOR_BYTES))
    report = led.report()
    report.update({
        "parameters": {
            "N_log2": round(math.log2(N), 6), "square_slots": S, "r_a": R_A, "s": float(s),
            "V": float(V), "walk_steps_T_log2": round(math.log2(T), 6),
            "total_steps_log2": round(math.log2(total_steps), 6), "distinguished_points_log2": round(math.log2(dps), 6),
            "dp_bits": DP_BITS, "walks": WALKS,
            "adds_per_step": float(adds_per_step), "sqrs_per_step": float(sqrs_per_step),
            "cycle_events_per_step_upper95": float(rate), "window": WINDOW, "wasted_fraction_upper": float(waste),
            "trail_steps": WALKS * 2 ** DP_BITS, "step_units": float(step_units),
            "optimal_square_slots_at_c2": choose_square_slots(C2, KAPPA),
        },
        "memory_log2_bytes": str(exact.log2_up(max(1, peak_bytes))),
        "success": exact.birthday_success(T, N, eps=1 - V, delta=DELTA),
        "success_if_waste_not_budgeted": exact.birthday_success(math.floor(T * float(1 - waste)), N, eps=1 - V, delta=DELTA),
        "c2": float(C2), "kappa": float(KAPPA),
    })
    return report


if __name__ == "__main__":
    print(json.dumps(build(), indent=2))
