def v_rate(s):
    """Collision rate for square fraction s (S = s r_a square slots): 1 - s^2 - (1 - s) / r_a. The
    r_a - S additive adders are each selected with probability 1/r_a; the square branch with probability s."""
    return 1 - s * s - (1 - s) / R_A


def union_log2(ell, s):
    """log2 of the union bound on the probability that a window of ell consecutive steps is a formal
    cancellation: all steps additive, and for each adder h the multiset of rotations of h decomposes into
    2-gons {k, k + 6} and 3-gons {k, k + 4, k + 8} (walk-spec section 9, Proposition G). Per partition of the
    window into gon blocks, each block costs its free first step and its partners: 1/6792 per partner cell for a
    2-gon, 1/6792^2 for a 3-gon with its two partners. Sum over partitions of ell labelled positions into a
    2-blocks and b 3-blocks, with the 2^b orientation factor of the 3-gon:
        (1 - s)^ell * sum_{2a + 3b = ell} ell! / (2^a a! 6^b b!) * 2^b * 6792^(-(a + 2b)).
    """
    terms = []
    for b in range(ell // 3 + 1):
        if (ell - 3 * b) % 2:
            continue
        a = (ell - 3 * b) // 2
        lt = (math.lgamma(ell + 1) - (a * math.log(2) + math.lgamma(a + 1)) - (b * math.log(6) + math.lgamma(b + 1))
              + b * math.log(2) - (a + 2 * b) * math.log(ADDITIVE_CELLS))
        terms.append(lt / math.log(2))
    mx = max(terms)
    return ell * math.log2(1 - float(s)) + mx + math.log2(sum(2 ** (t - mx) for t in terms))


def event_rate_bound(s):
    """Upper bound on the probability per main step that a cycle is detected (any length up to 64):
    the 2-cycle rate (1 - s)/(12 * 1024) for a window that returns to the state two steps back, plus the
    formal windows of length 3 to 64 (union bound), plus the non-formal closures (1 / r per candidate).
    The 2-cycle term is exact under the uniform-choice model; the measured 2-cycle count is 4.5076e-5 per
    step against this 4.4982e-5 term (ratio 1.0021)."""
    two = (1 - float(s)) / (12 * R_A)
    formal = sum(2 ** union_log2(ell, s) for ell in range(3, 65))
    nonformal = 12 * 64 / R
    return two + formal + nonformal


def trap_bound(s):
    """Per-step probability that an undetected cycle (length 65 to CAP) closes. Two parts:
    (a) formal windows (all steps additive, decomposable into gons): union bound for lengths 65..400
        (union_log2) and, for longer windows, the probability that all steps are additive, (1 - s)^ell;
    (b) non-formal closures: a closure whose exponent coefficient is nonzero is an event of probability
        1/r for uniform coins (heuristic H5), over 12 candidates (class powers) per length and per step.
    The coefficient of a window containing a square is 2^q lambda^J - 1 type data with q at most the window
    length; it is nonzero because 2^q is not a 12th root of unity for q < 2^247 (number_theory.py), so such a
    window falls under (b).
    """
    union = sum(2 ** union_log2(ell, s) for ell in range(65, 401))
    additive_tail = float(1 - s) ** 401 / float(s)
    nonformal = 12 * CAP / R
    per_step = union + additive_tail + nonformal
    return {"union_65_400": union, "additive_tail_401": additive_tail, "nonformal_per_step": nonformal,
            "per_step": per_step}


def fresh_steps_needed(V, delta, f):
    """Fresh steps T with 1 - exp(-f tau) - delta >= TARGET, tau = T^2 V / (2N)."""
    tau = -math.log(1 - float(TARGET) - delta) / f
    return math.ceil(math.sqrt(2 * N * tau / float(V)) * (1 + 1e-12))


def cap_loss(c):
    """Fraction of collisions lost to the trail cap: 2 (1 + c) e^(-c)."""
    return 2 * (1 + c) * math.exp(-c)


def dp_capacity(M):
    """Capacity D of the distinguished-point table for M main steps (walk-spec section 9.4).

    A walk's trail ends at its first distinguished point (DP), where it stores the record and restarts at its
    own start element. Every record is then either a fresh DP flag (a state no walk has visited; its key is
    uniform given the past under H7, so the flag has probability 2^-60) or a duplicate: a walk that has joined
    another walk's trail (its next state is a state of that trail) reaches the same DP once, and then restarts.
    A walk joins at most once per trail, so the duplicates are at most the joins J, pathwise. Hence the records
    are at most X + J, where X is the number of fresh flags. X is dominated by Binomial(M, 2^-60), and J by
    Binomial(M, M / N) (a step's next state is a visited state with probability at most (visited)/N <= M/N, H1).
    Capacity D = ceil(2 mu) + JOIN_ALLOWANCE with mu = M 2^-60: overflow requires X > 2 mu or J > 64.
    """
    mu = Fraction(M, 2 ** DP_BITS)
    return math.ceil(2 * mu) + JOIN_ALLOWANCE


def dp_slots(capacity):
    """Smallest power of two >= capacity: the number of slots of the bitonic network (padding with +infinity)."""
    return 1 << max(0, (capacity - 1).bit_length())


def bitonic_comparators(n):
    """Compare-exchanges of the bitonic sorting network on n = 2^k slots: n k (k + 1) / 4."""
    k = n.bit_length() - 1
    assert n == 1 << k
    return n * k * (k + 1) // 4


def log2_chernoff(mu, eps):
    """log2 of exp(-eps^2 mu / 3): the multiplicative Chernoff tail for a count with mean mu."""
    return -(float(eps) ** 2) * mu / 3 / math.log(2)


def number_theory_values():
    res = number_theory.check()
    assert res["r_minus_1_product_ok"] and res["factor_primes_ok"] and res["order_bits"] == 251
    assert res["q0_bits"] == 248
    return {k: (str(v) if isinstance(v, int) and not isinstance(v, bool) else v) for k, v in res.items()}


def build():
    nt = number_theory_values()
    S = MEASURED_S
    s = Fraction(S, R_A)
    V = v_rate(s)
    f = 1 - cap_loss(CAP_C)
    p_ev = event_rate_bound(s) * (1 + float(EPS_EV))
    assert p_ev <= 4.6e-5, p_ev
    # Revisit steps: every closure event (first revisit of a window state of its own trail) is followed by at most
    # WINDOW revisit steps before its detection (the anchor fires within 127 steps of entry); a join is followed by
    # the rest of the joined trail, at most CAP steps, and there are at most JOIN_ALLOWANCE joins (failure below).
    w = WINDOW * p_ev + 2.0 ** -50                      # waste fraction: closure revisits, plus join suffixes (asserted below)
    lag = WALKS * 2 ** DP_BITS                          # detection lag: each walk runs to its next DP before a collision is seen
    # Realised square fraction over the first M steps: Hoeffding over the fresh steps (EPS_SQ), revisit steps (WINDOW
    # per closure event, the closure count is bounded by p_ev with slack), and the join suffixes (JOIN_ALLOWANCE CAP / M).
    eps_s = float(EPS_SQ) + WINDOW * p_ev + 2.0 ** -50
    V_low = min(v_rate(float(s) - eps_s), v_rate(float(s) + eps_s))
    trap = trap_bound(s)
    delta = 0.0
    for _ in range(6):                                  # the failure terms depend on M, M on the failure terms
        T = fresh_steps_needed(V_low, delta, f)
        M = math.ceil((T + lag) / (1 - w))
        assert JOIN_ALLOWANCE * CAP / M <= 2.0 ** -50, M
        mu_dp = Fraction(M, 2 ** DP_BITS)
        mu_join = Fraction(M * M, N)                    # mean bound for J: M steps, each a join with probability <= M / N
        delta_trap = M * trap["per_step"]
        failures = {
            "trap_formal_and_nonformal": delta_trap,
            "fingerprint_markov": 2.0 ** -60,
            "square_fraction_hoeffding_log2": -2 * float(EPS_SQ) ** 2 * M / math.log(2),
            "cycle_count_blocking_log2": math.log2(64) + log2_chernoff(p_ev * M / 64, EPS_EV),
            "nonformal_short_expectation": 12 * 64 * M / R,
            "dp_fresh_flags_overflow_log2": log2_chernoff(mu_dp, 1),
            "join_allowance_log2": JOIN_ALLOWANCE * math.log2(math.e * float(mu_join) / JOIN_ALLOWANCE),
        }
        delta = (failures["trap_formal_and_nonformal"] + failures["fingerprint_markov"]
                 + 2.0 ** failures["square_fraction_hoeffding_log2"] + 2.0 ** failures["cycle_count_blocking_log2"]
                 + failures["nonformal_short_expectation"] + 2.0 ** failures["dp_fresh_flags_overflow_log2"]
                 + 2.0 ** failures["join_allowance_log2"])
    D = dp_capacity(M)
    n_slots = dp_slots(D)
    dp_inst = (DP_STORE_INST * D + RESTART_INST * D + SORT_CMP_INST * bitonic_comparators(n_slots)
               + SORT_SCAN_INST * n_slots + OVERFLOW_INST * D)
    dp_units = dp_inst / C
    event_charge = Fraction(p_ev).limit_denominator(10 ** 12) * EVENT_OPS * A_UNITS
    # Every main step is charged the worst case of the two step types, A_UNITS (A_UNITS > Q_UNITS).
    components = {
        "walk_steps": M * A_UNITS,
        "detected_cycles": M * event_charge,
        "adder_table": R_A * (2 * EXP_UNITS + 12 * FROBENIUS_UNITS),
        "walk_starts": WALKS * 2 * EXP_UNITS,
        # Restarts at a DP (at most D) and at the trail cap (at most M / CAP): one multiplication each (charged A).
        "restarts_trail_cap": (M // CAP) * A_UNITS,
        "distinguished_points": dp_units,
        "fingerprint_verification": 2 ** 60 * Fraction(D * D, 2 ** (FINGERPRINT_BITS + 1)) * EXP_UNITS,
        "solve_verify_output": Fraction(SOLVE_INSTRUCTIONS, C),
    }
    W_max = sum(components.values())

    tau_eff = float(T) ** 2 * float(V_low) / (2 * float(N))
    success_model = 1 - math.exp(-f * tau_eff)
    success_lower = success_model - delta
    success_uncharged = 1 - math.exp(-f * tau_eff * (1 - w) ** 2) - delta

    score = exact.log2_up(W_max)
    peak_bytes = (n_slots * DP_BYTES + DP_BYTES                       # table (padded to n slots) and one swap record
                  + 12 * R_A * (ELEMENT_BYTES + 2 * EXPONENT_BYTES)   # adder table
                  + WALKS * (2 * ELEMENT_BYTES + 2 * EXPONENT_BYTES + DETECTOR_BYTES)  # walk states and detectors
                  + WALKS * (ELEMENT_BYTES + 2 * EXPONENT_BYTES))     # per-walk start elements (restart)
    report = {
        "components_log2_units": {k: round(exact.log2(v), 6) for k, v in components.items()},
        "time_log2": str(score),
        "time_log2_decimal": float(score),
        "time_log2_float": exact.log2(W_max),
        "score_rational": {"numerator": str(score.numerator), "denominator": str(score.denominator)},
        "preprocessing_log2": str(exact.log2_up(components["adder_table"] + components["walk_starts"])),
        "parameters": {
            "N_log2": round(math.log2(N), 6), "square_slots": S, "r_a": R_A, "s": float(s),
            "V": float(V), "V_low": V_low, "square_fraction_deviation": eps_s,
            "walk_steps_T_log2": round(math.log2(T), 6),
            "main_steps_log2": round(math.log2(M), 6), "lag_steps_log2": round(math.log2(lag), 6),
            "dp_capacity_records": D, "dp_capacity_log2": round(math.log2(D), 6),
            "dp_slots_log2": round(math.log2(n_slots), 6), "dp_comparators_log2": round(math.log2(bitonic_comparators(n_slots)), 6),
            "dp_bits": DP_BITS, "walks": WALKS,
            "step_charge": float(A_UNITS), "event_charge": float(event_charge),
            "event_rate_bound": p_ev, "window": WINDOW, "wasted_fraction_charged": w,
            "trail_cap_log2_steps": round(math.log2(CAP), 6), "detection_factor": f,
            "fingerprint_bits": FINGERPRINT_BITS, "false_pairs_mean_log2": round(math.log2(float(Fraction(D * D, 2 ** (FINGERPRINT_BITS + 1)))), 6),
            "join_mean_bound_log2": round(math.log2(float(mu_join)), 6),
            "restart_inst": str(RESTART_INST),
            "dp_store_inst": str(DP_STORE_INST),
            "sort_cmp_inst": str(SORT_CMP_INST), "sort_scan_inst": str(SORT_SCAN_INST),
        },
        "number_theory": nt,
        "trap_bound": trap,
        "failure_terms": failures,
        "delta_total": delta,
        "memory_log2_bytes": str(exact.log2_up(max(1, peak_bytes))),
        "success": {"tau_eff": tau_eff, "eps": float(1 - V_low), "model": success_model,
                    "delta": delta, "lower_bound": success_lower},
        "success_if_waste_not_charged": success_uncharged,
        "a_units": float(A_UNITS), "q_units": float(Q_UNITS), "dp_units_per_record": float(dp_units / D),
        "kappa": float(KAPPA),
    }
    return report


