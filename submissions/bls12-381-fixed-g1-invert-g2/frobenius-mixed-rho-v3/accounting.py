    """Exact multiplicative order of base modulo a prime, given the complete factorisation of n = modulus - 1.

    Start from o = n (so base^o = 1). For each prime p, remove factors of p while base^(o/p) = 1; then
    v_p(o) equals v_p(order) for every p, so o is the order. The certificate checked by check() is
    base^o = 1 and base^(o/p) != 1 for every prime p dividing o.
    """
    o = n
    for p, e in primes_with_exponent:
        for _ in range(e):
            if o % p == 0 and pow(base, o // p, modulus) == 1:
                o //= p
    return o


