import operator
import random

from cscore import rho

MIX_P = (1 << 127) - 1
MIX_A = 0x9E3779B97F4A7C15D1B54A32D192ED03
MIX_B = 0x632BE59BD9B4E019F1357BD8A2C6D4E3
