# ---- entrypoint: gt_rho.py ----

"""Toy test of the Frobenius-class GT walk (cscore.gt): success curve, solves, cycle rates.

Input (JSON on stdin): bits (group order ell >= 2^bits), trials, s (square probability
of the mixed walk, 0 for add-only), adder_bits, dp_bits, walks, seed.

Every trial draws a uniform secret y, builds the instance z = g^y, runs the walk
round-robin on the order-ell subgroup of F_{q^12}^* up to the first useful collision,
then solves end to end through distinguished points and checks g^y' = z.

Model under test (RESEARCH.md 3.4-3.5): with N = (ell - 1)/12 classes and collision
rate V = 1 - s^2 - (1 - s)^2 / r_a, tau = T^2 V / (2N) is Exp(1) distributed, so
P[tau <= t] = 1 - exp(-t). The experiment reports the empirical CDF of tau against it.

Toy scale only: tests the collision statistics of the walk, not production cost.
"""
import json
import math
import random
import sys
import time

from cscore import gt, stats

TAUS = [0.25, 0.5, 0.5277, 0.75, 1.0, 1.5, 2.0]  # 0.5277 >= tau for model success 0.41 + DELTA


def main():
    started = time.time()
    cfg = json.load(sys.stdin)
    for k, v in gt.DEFAULTS.items():
        cfg.setdefault(k, v)
    G = gt.ToyGT(1 << cfg["bits"], seed=cfg["seed"])
    rng = random.Random(cfg["seed"])
    rows = [gt.trial(G, cfg, rng) for _ in range(cfg["trials"])]

    N = (G.m - 1) // gt.DEG
    r_a = 1 << cfg["adder_bits"]
    s_eff = round(cfg["s"] * r_a) / r_a
    V = 1 - s_eff * s_eff - (1 - s_eff) ** 2 / r_a
    solved = [r for r in rows if r["first_useful"] is not None]
    taus = [r["first_useful"] ** 2 * V / (2 * N) for r in solved]
    m = len(rows)
    cdf = []
    for t in TAUS:
        k = sum(1 for x in taus if x <= t)
        cdf.append({"tau": t, "empirical": round(k / m, 4), "wilson95": stats.wilson(k, m),
                    "model_exp1": round(1 - math.exp(-t), 4)})
    steps = sum(r["solved_at"] or 0 for r in rows)
    out = {
        "group": {"q": G.q, "ell": G.m, "classes_N": N, "lambda": G.lam,
                  "field_modulus_low_coeffs": G.field.f},
        "config": cfg,
        "walk": {"r_a": r_a, "square_slots": round(cfg["s"] * r_a), "s_effective": s_eff,
                 "V": round(V, 6)},
        "trials": m,
        "solved": len(solved),
        "all_solutions_verified": all(r["correct"] for r in solved),
        "mean_tau": round(sum(taus) / len(taus), 4) if taus else None,
        "model_mean_tau": 1.0,
        "success_curve": cdf,
        "mean_detect_overhead_steps": round(sum(r["solved_at"] - r["first_useful"] for r in solved) / len(solved), 2)
        if solved else None,
        "total_steps": steps,
        "two_cycles_per_step": round(sum(r["two_cycles"] for r in rows) / steps, 6) if steps else None,
        "long_cycles_per_step": round(sum(r["long_cycles"] for r in rows) / steps, 6) if steps else None,
        "cycle_step_fraction": round(sum(r["cycle_steps"] for r in rows) / steps, 6) if steps else None,
        "predicted_two_cycles_per_step_RESEARCH_3_5": round((1 - s_eff) ** 2 / (gt.DEG * r_a), 6),
        "scope": "toy group only; tests the collision statistics and the solver, not production cost",
        "elapsed_seconds": round(time.time() - started, 2),
    }
    print(json.dumps(out))


if __name__ == "__main__":
    main()
