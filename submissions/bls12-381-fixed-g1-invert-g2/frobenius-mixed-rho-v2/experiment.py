import math

from cscore import stats

MAX_CYCLE = 64
ANCHOR_PERIOD = 64


class Walk:
    def __init__(self, group, n, canon, adders, adder_bits, dp_bits):
        self.E, self.n, self.canon = group, n, canon.canon
        self.adders = adders
        self.mask = (1 << adder_bits) - 1
        self.adder_bits = adder_bits
        self.dp_mask = (1 << dp_bits) - 1

    def f(self, W, a, b):
        R, c, d = self.adders[self.E.key(W) & self.mask]
        S = self.E.add(W, R)
        if S is None:
            return None, 0, 0
        return self.canon(S, (a + c) % self.n, (b + d) % self.n)

    def escape(self, cycle):
        """Deterministic exit from a fruitless cycle: double its smallest-key element."""
        W, a, b = min(cycle, key=lambda e: self.E.key(e[0]))
        S = self.E.add(W, W)
        if S is None:
            return None, 0, 0
        return self.canon(S, 2 * a % self.n, 2 * b % self.n)

    def is_dp(self, W):
        return (self.E.key(W) >> self.adder_bits) & self.dp_mask == 0


def solve(n, a1, b1, a2, b2):
    if (b1 - b2) % n == 0:
        return None
    return (a2 - a1) * pow(b1 - b2, -1, n) % n


