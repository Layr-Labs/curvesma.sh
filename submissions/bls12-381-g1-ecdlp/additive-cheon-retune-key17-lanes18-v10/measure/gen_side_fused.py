#!/usr/bin/env python3
"""Generate side_fused.S: blst's internal AArch64 Montgomery routines (verbatim,
renamed with the prefix sk_) plus the fused side-output driver.

usage: python3 gen_side_fused.py <blst checkout at f7a88067> > side_fused.S

Copied verbatim from build/elf/mul_mont_384-armv8.S (Apache-2.0, Supranational):
  __mul_mont_384, __sqr_384, __mul_by_1_mont_384.
The driver below is new; it inlines blst's __redc_tail_mont_384 without its
three result stores.
"""
import re, sys

src = open(sys.argv[1].rstrip("/") + "/build/elf/mul_mont_384-armv8.S").read()

def block(name):
    e = re.escape(name)
    m = re.search(r"^%s:\n(.*?)^\.size\t%s,\.-%s\n" % (e, e, e), src, re.S | re.M)
    if not m:
        raise SystemExit("routine %s not found" % name)
    body = m.group(1)
    assert not re.search(r"^\.L|^[A-Za-z_]\w*:", body, re.M), "unexpected label in " + name
    new = "sk_" + name.lstrip("_")
    return ".type\t%s,%%function\n.align\t5\n%s:\n%s.size\t%s,.-%s\n" % (new, new, body, new, new)

print("""// side_fused.S -- generated by gen_side_fused.py; do not edit by hand.
// Routines sk_mul_mont_384, sk_sqr_384, sk_mul_by_1_mont_384 are blst's
// __mul_mont_384, __sqr_384, __mul_by_1_mont_384 (commit f7a88067,
// build/elf/mul_mont_384-armv8.S), copied verbatim and renamed.
#ifndef __SIZEOF_POINTER__
#define __SIZEOF_POINTER__ 8
#endif
.text
""")
for name in ("__mul_mont_384", "__sqr_384", "__mul_by_1_mont_384"):
    print(block(name))

print(open(sys.argv[0].replace("gen_side_fused.py", "side_driver.S.in")).read())
