# Generates side_fused.S (twin-ap-v3 fused side output kernel) from blst's generated AArch64 assembly.
# Usage: python3 gen_side_fused.py <blst checkout at f7a88067ed98385ebc6cf41ccecf21ead706a5b7> > side_fused.S
import sys
A=['x11','x12','x13','x14','x15','x16']; B=['x19','x20','x21','x22','x23','x24']
P6=('x5','x6','x7','x8','x9','x10')
def sub_mod(dst, src, masks, borrow):            # dst = dst - src mod p, both in [0, p): blst's __sub_mod_384 sequence
    a,b,m=dst,src,masks; L=[f"\tsubs\t{a[0]},{a[0]},{b[0]}"]+[f"\tsbcs\t{a[k]},{a[k]},{b[k]}" for k in range(1,6)]
    L.append(f"\tsbc\t{borrow},xzr,xzr"); L+= [f"\tand\t{m[k]},{P6[k]},{borrow}" for k in range(6)]
    L.append(f"\tadds\t{a[0]},{a[0]},{m[0]}"); L+=[f"\tadcs\t{a[k]},{a[k]},{m[k]}" for k in range(1,5)]; L.append(f"\tadc\t{a[5]},{a[5]},{m[5]}")
    return "\n".join(L)
def sub_plain(dst, src):                         # dst = dst - src as integers (caller guarantees no borrow out)
    return "\n".join([f"\tsubs\t{dst[0]},{dst[0]},{src[0]}"]+[f"\tsbcs\t{dst[k]},{dst[k]},{src[k]}" for k in range(1,6)])
def add_plain(dst, src):                         # dst = dst + src as integers (caller guarantees no carry out)
    return "\n".join([f"\tadds\t{dst[0]},{dst[0]},{src[0]}"]+[f"\tadcs\t{dst[k]},{dst[k]},{src[k]}" for k in range(1,6)])
M=['x25','x26','x27','x28','x0','x1']
def ld6(regs, base, off=0):
    return "\n".join(f"\tldp\t{regs[2*k]},{regs[2*k+1]},[{base},#{off+16*k}]" for k in range(3))
drv=f"""// twin-ap-v3: fused side output of a twin step on AArch64 (generated by gen_side_fused.py).
// Computes y' = y(P - G) = mu (x' - x1) - y1, mu = (y1 + y2) i, x' = mu^2 - x1 - x2, i = 1/(x2 - x1),
// in blst's Montgomery representation (R = 2^384), for P = (x1, y1), G = (x2, y2) with x1, y1, x2, y2, i in [0, p).
// The four field routines after the driver are verbatim copies of blst's private AArch64 routines
// __mul_mont_384, __sqr_384, __mul_by_1_mont_384 and __redc_tail_mont_384 (supranational/blst at
// f7a88067ed98385ebc6cf41ccecf21ead706a5b7, build/elf/mul_mont_384-armv8.S, Apache-2.0), renamed with a tw prefix and __SIZEOF_POINTER__ written as 8,
// except that the three result stores at the end of __redc_tail_mont_384 are dropped (its result stays in x11..x16).
// The driver keeps operands in registers between them: one prologue, the modulus loaded twice (__sqr_384 overwrites x5..x10), the additions and
// subtractions inline, and only mu and the 768-bit square on the stack.
//
// Lazy reduction (proof.md Section 2): t = y1 + y2 is left in [0, 2p) and w = mu^2 + 3p - 2 x1 - x2 in [0, 4p);
// both are inputs a of the word-serial Montgomery multiplication __mul_mont_384 with b < p, for which the result
// before its final conditional subtraction is below a b / R + p < 4p^2/R + p < 2p (4p < 2^383 < R), so the single
// conditional subtraction returns the fully reduced product. y' is fully reduced into [0, p) by the last
// (modular) subtraction.
//
// C prototype: void tw_side_fused(limb_t out[12], const limb_t P[12], const limb_t G[12],
//                                 const limb_t inv[6], const limb_t p_and_3p[12], limb_t n0);
// p_and_3p = p followed by 3p (both < 2^384); only out[6..12) = y' is written.
.text
.globl\ttw_side_fused
.type\ttw_side_fused,%function
.align\t5
tw_side_fused:
\tstp\tx29,x30,[sp,#-128]!
\tadd\tx29,sp,#0
\tstp\tx19,x20,[sp,#16]
\tstp\tx21,x22,[sp,#32]
\tstp\tx23,x24,[sp,#48]
\tstp\tx25,x26,[sp,#64]
\tstp\tx27,x28,[sp,#80]
\tstp\tx5,x0,[sp,#96]\t\t// n0 where tw__mul_mont_384 reads it; out pointer
\tstr\tx4,[sp,#112]\t\t// pointer to p, 3p
\tsub\tsp,sp,#160\t\t// [sp,0..96) square, [sp,96..144) mu, [sp,144..160) P, G
\tstp\tx1,x2,[sp,#144]
\tmov\tx17,x3
{ld6(P6,'x4')}
// t = y1 + y2 in [0, 2p) (no reduction)
\tldp\tx11,x12,[x1,#48]
\tldp\tx19,x20,[x2,#48]
\tldp\tx13,x14,[x1,#64]
\tldp\tx21,x22,[x2,#64]
\tldp\tx15,x16,[x1,#80]
\tldp\tx23,x24,[x2,#80]
{add_plain(A,B)}
// mu = t i, fully reduced
\tmov\tx2,x17
\tldr\tx17,[x2]
\tldr\tx4,[x29,#96]
\tbl\ttw__mul_mont_384
\tstp\tx11,x12,[sp,#96]
\tstp\tx13,x14,[sp,#112]
\tstp\tx15,x16,[sp,#128]
// mu^2, fully reduced
\tmov\tx0,sp
\tbl\ttw__sqr_384
\tldr\tx2,[x29,#112]
{ld6(P6,'x2')}
\tldr\tx4,[x29,#96]
\tmov\tx1,sp
\tbl\ttw__mul_by_1_mont_384
\tbl\ttw__redc_tail_mont_384
// w = mu^2 + 3p - x1 - x1 - x2 in [0, 4p): every partial value stays in [0, 4p), no borrow or carry out
\tldr\tx2,[x29,#112]
{ld6(B,'x2',48)}
{add_plain(A,B)}
\tldr\tx1,[sp,#144]
{ld6(B,'x1')}
{sub_plain(A,B)}
{sub_plain(A,B)}
\tldr\tx2,[sp,#152]
{ld6(B,'x2')}
{sub_plain(A,B)}
// mu w, fully reduced
\tadd\tx2,sp,#96
\tldr\tx17,[x2]
\tldr\tx4,[x29,#96]
\tbl\ttw__mul_mont_384
// y' = mu w - y1 mod p, in [0, p)
\tldr\tx1,[sp,#144]
{ld6(B,'x1',48)}
{sub_mod(A,B,M,'x3')}
\tldr\tx0,[x29,#104]
\tstp\tx11,x12,[x0,#48]
\tstp\tx13,x14,[x0,#64]
\tstp\tx15,x16,[x0,#80]
\tadd\tsp,sp,#160
\tldp\tx19,x20,[x29,#16]
\tldp\tx21,x22,[x29,#32]
\tldp\tx23,x24,[x29,#48]
\tldp\tx25,x26,[x29,#64]
\tldp\tx27,x28,[x29,#80]
\tldp\tx29,x30,[sp],#128
\tret
.size\ttw_side_fused,.-tw_side_fused

// Test entry for the lazy-input claim: ret = a b / R mod p through tw__mul_mont_384, same frame as blst's
// mul_mont_384. C prototype: void tw_mul_mont_384(limb_t ret[6], const limb_t a[6], const limb_t b[6],
// const limb_t p[6], limb_t n0).
.globl\ttw_mul_mont_384
.type\ttw_mul_mont_384,%function
.align\t5
tw_mul_mont_384:
\tstp\tx29,x30,[sp,#-128]!
\tadd\tx29,sp,#0
\tstp\tx19,x20,[sp,#16]
\tstp\tx21,x22,[sp,#32]
\tstp\tx23,x24,[sp,#48]
\tstp\tx25,x26,[sp,#64]
\tstp\tx27,x28,[sp,#80]
\tstp\tx4,x0,[sp,#96]
\tldp\tx11,x12,[x1]
\tldr\tx17,[x2]
\tldp\tx13,x14,[x1,#16]
\tldp\tx15,x16,[x1,#32]
\tldp\tx5,x6,[x3]
\tldp\tx7,x8,[x3,#16]
\tldp\tx9,x10,[x3,#32]
\tbl\ttw__mul_mont_384
\tldr\tx30,[x29,#8]
\tstp\tx11,x12,[x2]
\tstp\tx13,x14,[x2,#16]
\tstp\tx15,x16,[x2,#32]
\tldp\tx19,x20,[x29,#16]
\tldp\tx21,x22,[x29,#32]
\tldp\tx23,x24,[x29,#48]
\tldp\tx25,x26,[x29,#64]
\tldp\tx27,x28,[x29,#80]
\tldr\tx29,[sp],#128
\tret
.size\ttw_mul_mont_384,.-tw_mul_mont_384

"""
src=open(sys.argv[1] + '/build/elf/mul_mont_384-armv8.S').read()
def grab(name):
    a=src.index('\n'+name+':\n'); b=src.index('.size\t'+name+',', a)
    return src[a+1:b]
out=[]
for n in ['__mul_mont_384','__sqr_384','__mul_by_1_mont_384','__redc_tail_mont_384']:
    body=grab(n).replace(n+':','tw'+n+':',1)
    if n=='__redc_tail_mont_384':
        tail="\tstp\tx11,x12,[x0]\n\tstp\tx13,x14,[x0,#16]\n\tstp\tx15,x16,[x0,#32]\n"
        assert body.count(tail)==1; body=body.replace(tail,"\t// (result stores dropped: the result stays in x11..x16)\n")
    out.append('.type\ttw%s,%%function\n.align\t5\n%s.size\ttw%s,.-tw%s\n'%(n,body,n,n))
inc='\n'.join(out).replace('__SIZEOF_POINTER__','8')
sys.stdout.write(drv+inc+'\n.section\t.note.GNU-stack,"",%progbits\n')
