#!/usr/bin/env python3
"""Generate side_lanes.S: the lane-loop side-output kernel with blst's internal
AArch64 Montgomery routines inlined (verbatim bodies, final `ret` dropped).

usage: python3 gen_side_lanes.py <blst checkout at f7a88067> > side_lanes.S

Copied verbatim from build/elf/mul_mont_384-armv8.S (Apache-2.0, Supranational):
  __mul_mont_384 (inlined twice), __sqr_384, __mul_by_1_mont_384 (once each).
Only the trailing `ret` of each body is removed; nothing else is edited. The
driver (side_lanes.S.in) is new.
"""
import re, sys

src = open(sys.argv[1].rstrip("/") + "/build/elf/mul_mont_384-armv8.S").read()

def body(name):
    e = re.escape(name)
    m = re.search(r"^%s:\n(.*?)^\.size\t%s,\.-%s\n" % (e, e, e), src, re.S | re.M)
    if not m:
        raise SystemExit("routine %s not found" % name)
    b = m.group(1)
    assert not re.search(r"^\.L|^[A-Za-z_]\w*:", b, re.M), "unexpected label in " + name
    lines = b.rstrip("\n").split("\n")
    while lines and not lines[-1].strip():
        lines.pop()
    assert lines[-1].strip() == "ret", name
    assert "ret" not in "\n".join(l.split("//")[0] for l in lines[:-1]).split(), name
    assert not re.search(r"\b(x18|x30)\b", "\n".join(lines)), name
    return "\t// ---- inlined blst %s (verbatim, ret dropped)\n%s\n\t// ---- end %s\n" % (
        name, "\n".join(lines[:-1]), name)

drv = open(sys.argv[0].replace("gen_side_lanes.py", "side_lanes.S.in")).read()
drv = drv.replace("@MUL@", body("__mul_mont_384")).replace("@SQR@", body("__sqr_384")) \
         .replace("@BY1@", body("__mul_by_1_mont_384"))
print("""// side_lanes.S -- generated by gen_side_lanes.py; do not edit by hand.
// Inlined bodies are blst's __mul_mont_384, __sqr_384, __mul_by_1_mont_384
// (commit f7a88067, build/elf/mul_mont_384-armv8.S), verbatim minus `ret`.
#ifndef __SIZEOF_POINTER__
#define __SIZEOF_POINTER__ 8
#endif
.text
""")
print(drv)
