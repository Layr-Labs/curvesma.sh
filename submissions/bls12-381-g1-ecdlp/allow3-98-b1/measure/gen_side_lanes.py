#!/usr/bin/env python3
"""Generate side_lanes.S: the lane-loop side-output kernel with blst's internal
AArch64 Montgomery routines inlined.

usage: python3 gen_side_lanes.py <blst checkout at f7a88067> > side_lanes.S

Bodies from build/elf/mul_mont_384-armv8.S (Apache-2.0, Supranational), with
only these mechanical edits (every one asserted below):
  __mul_mont_384 (inlined twice): verbatim, trailing `ret` dropped.
  __sqr_384: trailing `ret` dropped, its six result stores `stp ...,[x0...]`
    dropped, and x5 renamed x17 (x17 is otherwise unused there); the 768-bit
    square stays in registers (low half x17,x19..x23, high half x24..x28,x16).
  __mul_by_1_mont_384: trailing `ret` dropped, its three input loads from [x1]
    dropped, and its registers renamed by a fixed permutation so that it reads
    the low half where __sqr_384 left it and leaves the high half untouched.
The driver (side_lanes.S.in) is new.
"""
import re, sys

src = open(sys.argv[1].rstrip("/") + "/build/elf/mul_mont_384-armv8.S").read()

def raw(name):
    e = re.escape(name)
    m = re.search(r"^%s:\n(.*?)^\.size\t%s,\.-%s\n" % (e, e, e), src, re.S | re.M)
    if not m:
        raise SystemExit("routine %s not found" % name)
    b = m.group(1)
    assert not re.search(r"^\.L|^[A-Za-z_]\w*:", b, re.M), "unexpected label in " + name
    lines = b.rstrip("\n").split("\n")
    while lines and not lines[-1].strip():
        lines.pop()
    assert lines[-1].strip() == "ret", name
    lines = lines[:-1]
    code = "\n".join(l.split("//")[0] for l in lines)
    assert "ret" not in code.split(), name
    assert not re.search(r"\b(x18|x30)\b", code), name
    return lines

def wrap(name, lines, note):
    return "\t// ---- inlined blst %s (%s)\n%s\n\t// ---- end %s\n" % (name, note, "\n".join(lines), name)

def mul():
    return wrap("__mul_mont_384", raw("__mul_mont_384"), "verbatim, ret dropped")

def sqr():
    lines = raw("__sqr_384")
    st = [l for l in lines if re.match(r"\s*stp\s", l)]
    assert len(st) == 6 and all(re.search(r"\[x0(,#\d+)?\]", l) for l in st)
    keep = [l for l in lines if l not in st]
    code = "\n".join(l.split("//")[0] for l in keep)
    assert "[" not in code and not re.search(r"\b(x0|x17)\b", code)
    out = []
    for l in keep:
        ins, sep, com = l.partition("//")
        out.append(re.sub(r"\bx5\b", "x17", ins) + sep + com)
    return wrap("__sqr_384", out, "ret and the six result stores dropped; x5 renamed x17")

BY1_MAP = {"x11": "x17", "x12": "x19", "x13": "x20", "x14": "x21", "x15": "x22", "x16": "x23",
           "x19": "x0", "x20": "x1", "x21": "x3", "x22": "x11", "x23": "x12", "x24": "x13",
           "x25": "x14", "x26": "x15"}

def by1():
    lines = raw("__mul_by_1_mont_384")
    ld = [l for l in lines if re.match(r"\s*ldp\s", l)]
    assert len(ld) == 3 and all("[x1" in l for l in ld)
    keep = [l for l in lines if l not in ld]
    code = "\n".join(l.split("//")[0] for l in keep)
    assert "[" not in code and not re.search(r"\b(x0|x1|x2|x3|x17|x27|x28)\b", code)
    out = []
    for l in keep:
        ins, sep, com = l.partition("//")
        ins = re.sub(r"\bx(\d+)\b", lambda m: BY1_MAP.get(m.group(0), m.group(0)), ins)
        out.append(ins + sep + com)
    code = "\n".join(l.split("//")[0] for l in out)
    used = set(re.findall(r"\bx\d+\b", code))
    assert used <= {"x4", "x5", "x6", "x7", "x8", "x9", "x10", "x17", "x19", "x20", "x21", "x22",
                    "x23", "x0", "x1", "x3", "x11", "x12", "x13", "x14", "x15"}, used
    assert not used & {"x2", "x16", "x24", "x25", "x26", "x27", "x28"}
    return wrap("__mul_by_1_mont_384", out, "ret and its three input loads dropped; registers renamed "
                + ", ".join("%s->%s" % kv for kv in BY1_MAP.items()))

drv = open(sys.argv[0].replace("gen_side_lanes.py", "side_lanes.S.in")).read()
drv = drv.replace("@MUL@", mul()).replace("@SQR@", sqr()).replace("@BY1@", by1())
print("""// side_lanes.S -- generated by gen_side_lanes.py; do not edit by hand.
// Inlined bodies are blst's __mul_mont_384, __sqr_384, __mul_by_1_mont_384
// (commit f7a88067, build/elf/mul_mont_384-armv8.S) with the edits listed in
// gen_side_lanes.py.
#ifndef __SIZEOF_POINTER__
#define __SIZEOF_POINTER__ 8
#endif
.text
""")
print(drv)
