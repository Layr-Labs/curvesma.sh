"""Toy test of the Cheon-type walk (cscore.cheon) on a generic prime-order group.

Input (JSON on stdin):
  bits      size of the toy prime r (r = 1 mod 2^(k+3), 3 | r-1)
  k         d = 2^k, the auxiliary power used (A_d); must satisfy k < bits - 8
  trials    number of uniform secrets s in Z_r^*
  mult      number of walk multipliers (elements of H), default 64
  dp_bits   distinguished points have probability 2^-dp_bits
  trails    walk trails per family (tame and wild)
  use_mu    fold by mu6 (default true); false walks on H itself
  seed

Every trial recovers s from T, A_1, A_2, ..., A_(2^k) through cscore.cheon and checks it.
The output compares the empirical step distribution with the random-mapping model
for tame-wild collisions, P(S <= c sqrt(M)) = 1 - exp(-c^2/4), with M = N/6 classes.

Toy scale only: it checks the walk's correctness and collision statistics in a generic
group, not the cost of a BLS12-381 step.
"""
import json
import math
import random
import sys

from cscore import cheon


def wilson(k, n, z=1.96):
    if n == 0:
        return [0.0, 1.0]
    p = k / n
    den = 1 + z * z / n
    mid = (p + z * z / (2 * n)) / den
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
    return [round(mid - half, 4), round(mid + half, 4)]


def main():
    cfg = json.load(sys.stdin)
    cfg.setdefault("mult", cheon.DEFAULTS["mult"])
    cfg.setdefault("dp_bits", cheon.DEFAULTS["dp_bits"])
    cfg.setdefault("trails", cheon.DEFAULTS["trails"])
    cfg.setdefault("use_mu", True)
    cfg.setdefault("seed", 1)
    rng = random.Random(cfg["seed"])
    k = cfg["k"]
    r = cheon.find_prime_order(cfg["bits"], k, rng)
    N = (r - 1) >> k
    M = N // 6 if cfg["use_mu"] else N
    assert N % 6 == 0 and (r - 1) % (1 << k) == 0

    walk = {"mult": cfg["mult"], "dp_bits": cfg["dp_bits"], "trails": cfg["trails"]}
    steps, recovered, wrong, dps = [], 0, 0, 0
    for _ in range(cfg["trials"]):
        orc = cheon.Oracle(r, rng, use_mu=cfg["use_mu"])
        s = rng.randrange(1, r)
        T = orc.point(s)
        powers = {1 << j: orc.point(pow(s, 1 << j, r)) for j in range(k + 1)}
        got, st = cheon.recover_scalar(orc, T, powers, k, rng, walk)
        wrong += st["wrong"]
        dps += st["dps"]
        if got == s:
            recovered += 1
        steps.append(st["steps"])
    steps.sort()

    sq = math.sqrt(M)
    tau_39 = -math.log(1 - 0.39)
    budget = 2 * math.sqrt(tau_39 * M)
    within = sum(1 for x in steps if x <= budget)
    claim_budget = 2 * math.sqrt(0.6 * M)        # the accounting's budget (proof.md section 2)
    within_claim = sum(1 for x in steps if x <= claim_budget)
    cdf = []
    for c in (0.5, 1.0, 2 * math.sqrt(tau_39), 2.0, 3.0):
        emp = sum(1 for x in steps if x <= c * sq) / len(steps)
        cdf.append({"c": round(c, 4), "empirical": round(emp, 4),
                    "model": round(1 - math.exp(-c * c / 4), 4)})

    out = {
        "r_bits": r.bit_length(),
        "k": k,
        "N_log2": round(math.log2(N), 4),
        "M_log2": round(math.log2(M), 4),
        "config": cfg,
        "recovered": recovered,
        "trials": cfg["trials"],
        "wrong_collisions": wrong,
        "dps_total": dps,
        "steps_median": steps[len(steps) // 2],
        "steps_over_sqrtM": {"median": round(steps[len(steps) // 2] / sq, 4),
                             "mean": round(sum(steps) / len(steps) / sq, 4)},
        "success_at_budget_0.39": {"budget_over_sqrtM": round(2 * math.sqrt(tau_39), 4),
                                   "empirical": round(within / len(steps), 4),
                                   "wilson95": wilson(within, len(steps))},
        "success_at_claim_budget": {"budget_over_sqrtM": round(2 * math.sqrt(0.6), 4),
                                    "model": round(1 - math.exp(-0.6), 4),
                                    "empirical": round(within_claim / len(steps), 4),
                                    "wilson95": wilson(within_claim, len(steps))},
        "cdf_vs_model": cdf,
        "scope": "generic prime-order group toy (exponent-hidden labels); tests walk "
                 "correctness and collision statistics only",
    }
    print(json.dumps(out))


if __name__ == "__main__":
    main()
