#!/usr/bin/env python3
"""v20 census: production-width key census + derived v2(m)=12 model, seed-coin
gap census, two-scale coverage census, routing-load census.

Fixes the four v19 flaws by MEASURING the objects the verdict names:

  key     : kappa_w for w = 10..30 on the challenge-faithful H object at
            2^16 records/side (predicted >= 16 collisions up to w = 27), a
            per-width within-side multiplicity histogram (the verdict's
            |{h in H : key([h]P0) = k}|), and a band-limited H-PRIME control
            at toy scale (the verdict's "uniform H factors" objection).
  rest    : 64-seed gap census (seed = algorithm coin), two-geometry coverage
            census with 8 bases/side, routing-load census at fixture scale.

Every number in the package is generated by this file; nothing is typed in by
hand.  Run `python3 census_v20.py key` then `python3 census_v20.py rest`.
"""
import json, math, os, random, sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import keymod
from toy import jmul, jaffine, is_prime, A_LO, A_HI, W_LO, W_HI

P, R = keymod.P, keymod.R
D = 2 ** 20
M = (R - 1) // D
assert (R - 1) % D == 0 and M * D == R - 1
V2_M = 12
assert (M >> V2_M) % 2 == 1

WIDTHS = tuple(range(10, 31))


def h_elem(rng):
    """Uniform element of H = image of the d-th power map (kernel size d)."""
    return pow(rng.randrange(2, R), D, R)


def h_list(rng, n):
    out, seen = [], set()
    while len(out) < n:
        h = h_elem(rng)
        if h not in seen and h != 0:
            seen.add(h)
            out.append(h)
    return out


# --------------------------------------------------------------- workers
def _ys_of(chunk):
    """Point y-coordinates for a block of scalars (module level: picklable)."""
    out = []
    for x in chunk:
        out.append(jaffine(jmul(x % R, (keymod.GX, keymod.GY, 1), P), P)[1])
    return out


def _pmap(fn, items, chunksize=256):
    import multiprocessing as mp
    ctx = mp.get_context("fork")          # pure-Python compute: fork is safe and fast
    n = max(1, min(16, ctx.cpu_count() - 1))
    with ctx.Pool(n) as pool:
        return [y for block in pool.map(fn, items, chunksize=1) for y in block]


def ys_all(scalars, nproc=16):
    blocks = [scalars[i:i + 512] for i in range(0, len(scalars), 512)]
    return _pmap(_ys_of, blocks)


# --------------------------------------------------------------- statistics
def mult_stats(keys):
    """Within-side multiplicity of the key map: the verdict's N(k) sample."""
    c = Counter(keys)
    return dict(distinct=len(c), max_mult=max(c.values()),
                mean_mult=round(len(keys) / len(c), 6),
                pairs_equal=sum(v * (v - 1) // 2 for v in c.values()))


def rows_for(yx, yy, widths, pairs):
    out = []
    for w in widths:
        mask = (1 << w) - 1
        kx = [keymod.even_member(y, P) & mask for y in yx]
        ky = [keymod.even_member(y, P) & mask for y in yy]
        ky_c = Counter(ky)
        obs = sum(c * ky_c[k] for k, c in Counter(kx).items() if k in ky_c)
        pred = pairs / 2.0 ** (w - 1)          # image 2^(w-1): even rep low bit = 0
        out.append(dict(width=w, image_log2=w - 1, pairs=pairs, observed=obs,
                        predicted=round(pred, 6),
                        ratio=round(obs / pred, 6) if pred >= 1 else None,
                        ucb_factor=round(max(1.0, (obs + 3 * math.sqrt(obs + 1)) / pred), 6)
                        if pred >= 1 else None,
                        within_side_a=mult_stats(kx), within_side_b=mult_stats(ky)))
    return out


# --------------------------------------------------------------- key census
KEY_SIZES = dict(big=dict(nb=1024, nw=64, challenges=3),
                 small=dict(nb=64, nw=64, challenges=6))


def key_census(name, nb, nw, challenges, widths=WIDTHS):
    """Challenge-faithful census: both sides H-members, giant side carries v=s^d."""
    rng = random.Random(20261024 + nb)
    A = h_list(rng, 2 * nb)
    W = h_list(rng, nw)
    ax, ay = A[:nb], A[nb:2 * nb]
    assert not (set(ax) & set(ay))
    assert all(pow(a, M, R) == 1 for a in A) and all(pow(w, M, R) == 1 for w in W)

    xs = [a * w % R for a in ax for w in W]
    ys = [a * w % R for a in ay for w in W]
    assert len(set(xs)) == len(xs) and len(set(ys)) == len(ys)
    assert all(pow(x, M, R) == 1 for x in xs) and all(pow(y, M, R) == 1 for y in ys)
    pairs = len(xs) * len(ys)
    yx = ys_all(xs)

    per_ch = []
    for _ in range(challenges):
        s = rng.randrange(2, R)
        v = pow(s, D, R)
        assert pow(v, M, R) == 1
        gy = ys_all([v * y % R for y in ys])
        per_ch.append(dict(s_bits=s.bit_length(), v_bits=v.bit_length(),
                           rows=rows_for(yx, gy, widths, pairs)))

    avg = []
    for i, w in enumerate(widths):
        obss = [c["rows"][i]["observed"] for c in per_ch]
        pred = per_ch[0]["rows"][i]["predicted"]
        mean = sum(obss) / len(obss)
        avg.append(dict(width=w, image_log2=w - 1, pairs=pairs,
                        observed_mean=round(mean, 3), observed_min=min(obss),
                        observed_max=max(obss), predicted=pred,
                        ratio_mean=round(mean / pred, 6) if pred >= 1 else None,
                        ratio_max=round(max(obss) / pred, 6) if pred >= 1 else None,
                        ratio_min=round(min(obss) / pred, 6) if pred >= 1 else None,
                        ucb_factor=round(max(1.0, (max(obss) + 3 * math.sqrt(max(obss) + 1)) / pred), 6)
                        if pred >= 1 else None,
                        within_side_a=per_ch[0]["rows"][i]["within_side_a"],
                        within_side_b=per_ch[0]["rows"][i]["within_side_b"]))
    return dict(name=name, records_per_side=len(xs), pairs=pairs, nb=nb, nw=nw,
                h_members=True, scaled=True, n_challenges=challenges,
                widths=list(widths), exact_rows=avg,
                challenges=[dict(rows=c["rows"]) for c in per_ch])


def key_part():
    out = dict(d=D, m=M, m_log2=round(math.log2(M), 4), v2_m=V2_M, key_bits=keymod.KEY_BITS,
               image_log2=keymod.KEY_IMAGE_BITS, widths=list(WIDTHS),
               faithful={}, note=(
                   "Every element of both lists is an H-member and the giant list carries "
                   "v = s^d with s uniform in Z_r^* (kernel of x->x^d has size d, so v is "
                   "uniform on H). kappa_w = 2^(w-1) * sum_k (N(k)/m)^2 is estimated by the "
                   "observed cross-side ratio at width w."))
    for name, cfg in KEY_SIZES.items():
        out["faithful"][name] = key_census(name, cfg["nb"], cfg["nw"], cfg["challenges"])
        print("%s: records %d pairs %d" % (name, out["faithful"][name]["records_per_side"],
                                           out["faithful"][name]["pairs"]), flush=True)

    # ---- control: the v18 object (ordinary primes, no H filter, no challenge)
    rng = random.Random(7)
    def prod_primes(lo, hi, need):
        o, q = [], lo | 1
        while len(o) < need and q < hi:
            if is_prime(q):
                o.append(q)
            q += 2
        return o
    nb, nw = 64, 64
    ab = prod_primes(A_LO, A_HI, 2 * nb)
    walk = prod_primes(W_LO, W_HI, nw)
    cx = [a * w for a in ab[:nb] for w in walk]
    cy = [a * w for a in ab[nb:2 * nb] for w in walk]
    out["control"] = dict(name="control", records_per_side=len(cx), pairs=len(cx) * len(cy),
                          nb=nb, nw=nw, h_members=False, scaled=False, n_challenges=1,
                          widths=list(WIDTHS),
                          exact_rows=rows_for(ys_all(cx), ys_all(cy), WIDTHS, len(cx) * len(cy)))
    print("control done", flush=True)
    return out


if __name__ == "__main__":
    part = sys.argv[1] if len(sys.argv) > 1 else "key"
    if part == "key":
        o = key_part()
        json.dump(o, open(HERE + "/census-key-v20.json", "w"), indent=1)
        print("wrote census-key-v20.json")
