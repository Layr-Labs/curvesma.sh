#!/usr/bin/env python3
"""Text-to-object sync: every structural/numeric claim in the shipped prose is extracted FROM the
shipped object and asserted against the prose.  Writes text-sync.txt; exit 0 iff every row is Y.

What it reads
  object   : span.o, rebuilt from schedule.py build() by span_asm.py (clang + otool -t -v)
  listing  : span-disasm.txt (regenerated by span_asm.py)
  prose    : submission.json (claim statement + title), proof.md, public-note.md, README.md
  ledger   : experiment.py LEDGER / CLAIM / cost()

Usage: python3 text_sync.py [--control]
       --control writes a stale token into a copy of the note and the check MUST fail (teeth test).
"""
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import ast
import schedule    # noqa: E402


def build_object():
    subprocess.run([sys.executable, os.path.join(HERE, "span_asm.py"), "--keep"],
                   check=True, capture_output=True, cwd=HERE)
    dis = open(os.path.join(HERE, "span-disasm.txt")).read()
    n = lambda pat: int(re.search(pat, dis).group(1))
    ext = dict(
        charged=n(r"charged per iteration\s*:\s*(\d+)"),
        nonrefresh=n(r"\((\d+) non-refresh"),
        literal=n(r"literal machine instructions\s*:\s*(\d+)"),
        leaf=n(r"leaf body (\d+)"),
        prefix=n(r"prefix loop (\d+)"),
        stubs=n(r"exit stubs\s*:\s*(\d+) distinct"),
        row6=n(r"\| product \| batch-product transfer \| (\d+) \|"),
        pairs=n(r"(\d+) eligible pairs"),
        maxdist=n(r"max distance (\d+)"),
        bound=n(r"bound (\d+)"),
    )
    rows = []
    for line in dis.splitlines():
        f = [q.strip() for q in line.split("|")]
        if len(f) >= 5 and f[1].startswith("row ") and f[0].isdigit():
            rows.append((f[2], f[3]))
    ext["frame"] = int(rows[0][1].split("#")[-1], 0) if rows else 0
    ext["save"] = next(o for s, o in rows if s.startswith("stur x30"))
    ext["prod_store"] = next(o for s, o in rows if s.startswith("stur x8"))
    ext["prod_load"] = next(o for s, o in rows if s.startswith("ldur x8"))
    ext["entry"] = next(o for s, o in rows if s.startswith("sub sp"))
    ext["in_degree"] = re.search(r"in-degree \[([0-9, ]+)\]", dis).group(1)
    ext["avg"] = (63 * ext["nonrefresh"] + ext["charged"]) / 64.0
    ext["step_price"] = 1 + ext["avg"] / 2000.0
    return ext


def prose():
    d = json.load(open(os.path.join(HERE, "submission.json")))
    out = {"submission.json": d["claims"][0]["statement"] + "\n" + d["title"]}
    for f in ("proof.md", "public-note.md", "README.md"):
        p = os.path.join(HERE, f)
        out[f] = open(p).read() if os.path.exists(p) else ""
    return d, out


STALE = [r"\b128 (?:literal|machine|instructions)", r"\b127(?:\.046875|\b)", r"\b130(?:\.046875|\b)",
         r"19 instructions", r"19-instruction", r"19 in the row-6", r"frameless", r"\[x19,\s*-8\]", r"x19-8",
         r"126\.2405", r"126\.240\b", r"1\.0635", r"1\.0725", r"1\.5175", r"124 in the leaf", r"133 instructions"]


def check(control=False):
    ext = build_object()
    d, P = prose()
    note = P["public-note.md"]
    if control:
        note = note.replace("## 3. One price table", "128 instructions were charged.\n\n## 3. One price table")
        P["public-note.md"] = note
    allp = "\n".join(P.values())
    rows = []

    def add(claim, src, val, ok):
        rows.append((claim, src, str(val), "Y" if ok else "N"))
        return ok

    ok = True
    ok &= add("charged per iteration = 134", "span_asm/otool", ext["charged"], ext["charged"] == 134 and "134" in allp)
    ok &= add("non-refresh step = 131", "schedule ledger", ext["nonrefresh"], ext["nonrefresh"] == 131 and "131" in allp)
    ok &= add("literal instructions = 132 (126 leaf + 6 prefix)", "otool -t -v", "%d/%d/%d" % (ext["literal"], ext["leaf"], ext["prefix"]),
              ext["literal"] == 132 and ext["leaf"] == 126 and ext["prefix"] == 6 and "132 literal" in allp)
    ok &= add("row 6 = 20 (1 entry + 9 x + 9 y + 1 product)", "schedule row 6", ext["row6"], ext["row6"] == 1 and "20 instructions" in allp)
    ok &= add("frame = 16 bytes", "disasm row 0", ext["frame"], ext["frame"] == 16 and "16-byte" in allp or "16 bytes" in allp)
    norm = lambda t: t.replace("0x", "")
    ok &= add("link saved at [sp,#8]", "disasm row 1", ext["save"],
              "[sp, #8]" in norm(ext["save"]) and "[sp,#8]" in allp)
    ok &= add("product store/load [sp,#0]", "disasm rows", ext["prod_store"] + " / " + ext["prod_load"],
              ("[sp, #0]" in norm(ext["prod_store"]) or "[sp]" in ext["prod_store"])
              and ("[sp, #0]" in norm(ext["prod_load"]) or "[sp]" in ext["prod_load"])
              and "[sp,#0]" in allp)
    ok &= add("exit stubs = 5, in-degree 1,1,1,1,3", "branch table", "%d [%s]" % (ext["stubs"], ext["in_degree"]),
              ext["stubs"] == 5 and ext["in_degree"] == "1, 1, 1, 1, 3" and "1,1,1,1,3" in allp.replace(" ", ""))
    ok &= add("eligible pairs = 6, max distance 56, bound 134", "traffic_pairs",
              "%d/%d/%d" % (ext["pairs"], ext["maxdist"], ext["bound"]),
              ext["pairs"] == 6 and ext["maxdist"] == 56 and ext["bound"] == 134 and "56" in allp)
    ok &= add("64-cycle average = 131.046875", "(63*131+134)/64", "%g" % ext["avg"],
              abs(ext["avg"] - 131.046875) < 1e-9 and "131.046875" in allp)
    ok &= add("step price = 1.0655234375", "1 + avg/2000", "%.10f" % ext["step_price"],
              abs(ext["step_price"] - 1.0655234375) < 1e-12 and "1.0655234375" in allp)
    expsrc = open(os.path.join(HERE, "experiment.py")).read()
    claim = ast.literal_eval(re.search(r"^CLAIM = (\(\d+, \d+\))", expsrc, re.M).group(1))
    ledger = ast.literal_eval(re.search(r"^LEDGER = (\[.*?\])\n", expsrc, re.M | re.S).group(1))
    subtotal = sum(n for _, n in ledger)
    ok &= add("ledger subtotal = 131 (15 rows)", "experiment.py LEDGER", subtotal,
              subtotal == 131 and "131" in allp)
    ok &= add("experiment CLAIM = (1262433, 10000)", "experiment.py CLAIM", claim,
              claim == (1262433, 10000))
    ok &= add("claim = 126.2433, fraction 1262433/10000", "submission.json", "%s/%s" % (d["claims"][0]["score"]["numerator"], d["claims"][0]["score"]["denominator"]),
              d["claims"][0]["score"] == {"numerator": "1262433", "denominator": "10000"}
              and "126.2433" in allp and d["claims"][0]["statement"].count("126.2433") >= 2)
    import math
    ok &= add("score rational reduced (gcd = 1)", "math.gcd", math.gcd(1262433, 10000), math.gcd(1262433, 10000) == 1)
    hits = []
    for pat in STALE:
        for f, txt in P.items():
            for m in re.finditer(pat, txt):
                hits.append("%s:%s" % (f, m.group(0)))
    ok &= add("no stale token (128/127/130/19-instruction/frameless/[x19,-8]/126.2405/1.0635/1.0725/1.5175)",
              "grep over shipped prose", "%d hits" % len(hits), not hits)

    width = max(len(r[0]) for r in rows)
    lines = ["text-to-object sync (v31) -- every claim phrase vs the shipped object",
             "=" * 100,
             "object: span.o rebuilt from schedule.py build(); otool -t -v; span-disasm.txt",
             ""]
    head = "%-3s %-*s | %-28s | %-24s | %s" % ("#", width, "claim phrase", "source of truth", "extracted", "ok")
    lines += [head, "-" * len(head)]
    for i, (c, s, v, o) in enumerate(rows, 1):
        lines.append("%-3d %-*s | %-28s | %-24s | %s" % (i, width, c, s, v, o))
    if hits:
        lines += ["", "stale-token hits:"] + ["  " + h for h in hits[:20]]
    lines += ["", "ALL CHECKS PASS" if ok else "FAILED"]
    open(os.path.join(HERE, "text-sync.txt"), "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0 if ok else 1


if __name__ == "__main__":
    if "--control" in sys.argv:
        tmp = tempfile.mkdtemp()
        # run the same check against a mutated note by monkeypatching the reader
        real = prose
        def patched():
            d, P = real()
            P["public-note.md"] = P["public-note.md"].replace("## 3. One price table", "128 instructions.\n\n## 3. One price table")
            return d, P
        globals()["prose"] = patched
        rc = check()
        shutil.rmtree(tmp, ignore_errors=True)
        print("\ncontrol: expected FAILED, got %s" % ("FAILED" if rc else "PASS -> CONTROL BROKEN"))
        sys.exit(0 if rc else 1)
    sys.exit(check())
