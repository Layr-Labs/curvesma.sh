TERM1 = 2.0 ** LOG2_TERM1 if LOG2_TERM1 > -1000 else 0.0
TERM2 = math.exp(-float((n_steps - 128 * k_close) * THETA))   # (1-theta)^m <= exp(-theta m)
TERM3 = float(TRAIL_MAX) * 2.0 ** -230
P_ABANDON = TERM1 + TERM2 + TERM3
E_ABANDON = float(TRAILS) * P_ABANDON                  # expected abandoned trails
DELTA_ABANDON = E_ABANDON / float(K)                   # Markov: P[more than K abandonments] <= E / K

# Within-trail coincidences (proof.md section 3, Lemma G, degenerate pairs, adder table): DELTA_LOOP.
DELTA_LOOP_DEG = TRAILS * Fraction(TRAIL_MAX * TRAIL_MAX, 2) * GROUP * Fraction(2, r)
DELTA_LOOP_NONDEG = TRAILS * Fraction(TRAIL_MAX * TRAIL_MAX, 2) * GROUP * Fraction(1, r - GROUP * TRAIL_MAX)
DELTA_LOOP_TABLE = Fraction(ADDERS * ADDERS * GROUP, r)
DELTA_LOOP_EXACT = DELTA_LOOP_DEG + DELTA_LOOP_NONDEG + DELTA_LOOP_TABLE
DELTA_LOOP = float(DELTA_LOOP_EXACT)

