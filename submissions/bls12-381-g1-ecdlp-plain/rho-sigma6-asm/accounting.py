P_CLOSE = RATE_TWO + RATE_LONG + 2 * RATE_FALSE        # p_c: per-step closure bound (both filters)
C_ABANDON = ADDERS                                     # c = 2^16
n_steps = 64 * (2 ** THETA_BITS + 1)                   # steps before abandonment, CAP_PERIODS = 2^DP_BITS
