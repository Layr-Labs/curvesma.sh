"""Exact accounting for the claim in proof.md (stdlib only; prints JSON).

All work is converted to target-group-operation equivalents. The walk does not use the
6M reference operation: every scalar AArch64 instruction of the attack, including all
field multiplications (bls_field.h), is charged at 1/C, C=2000. Integers and rationals are exact; logarithms are rounded
up to 6 decimals.
"""
import json
import math
from fractions import Fraction

from cscore.exact import Ledger, iroot_ceil, log2, log2_up

r = 0x73eda753299d7d483339d80809a1d80553bda402fffe5bfeffffffff00000001
C = 2000
ADDERS = 2 ** 16             # r-adding walk; index = bits 1..16 of the class key
K = 2 ** 30                  # walks (2^16 processors x 2^14-walk batches)
THETA_BITS = 60              # distinguished-point probability 2^-60
# A trail ends at its first distinguished point. A trail that crosses more than 2^60 anchor
# boundaries (64 steps apart) without one is abandoned, so every trail has fewer than
# TRAIL_MAX steps.
CAP = 64 * 2 ** THETA_BITS
TRAIL_MAX = CAP + 64

# Classes: N nonzero order-6 classes, plus one for the identity (never reached by a walk).
N = (r - 1) // 6 + 1

# Success model (proof.md section 2): 1 - exp(-tau*(1-eps)) - delta with tau = T^2/(2N).
# 2-cycles at most 1/A (Lemma C gives 1/(6 A)), 3..64-cycles at most 3/A^2 (Lemma C).
eps = Fraction(4, ADDERS) + 2 * Fraction(3, ADDERS) + 2 * Fraction(3 * 192, ADDERS ** 2)
delta = Fraction(1, 2 ** 20)
TAU_TARGET = Fraction(5303, 10000)
T_min = iroot_ceil(math.ceil(2 * N * TAU_TARGET), 2)
L = -(-T_min // K)                 # steps per walk counted towards the collision budget
T = K * L
S_max = K * (L + TRAIL_MAX)        # worst case: after L steps each walk finishes its current trail


# One unbatched step (affine add/double with its own inversion, adder selection and
# bookkeeping): measured 28,553.8 instructions on both input sets; 2^15 is charged.
UNBATCHED = 2 ** 15
# Charge per walk step (proof section 3). The common batched path is charged its measured
# whole-run instruction total per walk step, batch inversion included, taking the larger of the
# plain and anchor steps. The anchor measurement also contains its rare events, so this is a
# conservative charge. Rare events are metered at worst-case cost and covered by a Markov reserve.
C_COMMON = 2263
W_TWO = 2 * UNBATCHED + 2 ** 10              # 2-cycle check: confirmation and escape
W_LONG = 68 * UNBATCHED + 2 ** 10            # longer cycle: up to 65 look-ahead steps, then the escape
W_FALL = 2 ** 10                             # exact-k fallback
RATE_TWO = Fraction(1, ADDERS)               # per walk step, unconditional (H1), at most 1/A (H2)
RATE_LONG = Fraction(3, ADDERS ** 2)         # at most 3/A^2 (Lemma C)
RATE_FALL = Fraction(1, 2 ** 55)             # Lemma 1 margin
E_RARE = RATE_TWO * W_TWO + RATE_LONG * W_LONG + RATE_FALL * W_FALL   # expected rare work per walk step, upper bound
KM = 64                                      # Markov reserve factor: P[rare work > KM * E_RARE] <= 1/KM
RESERVE = KM * E_RARE
PER_STEP = C_COMMON + RESERVE                # charged instructions per walk step
step_units = PER_STEP / C
SCALAR_MUL = 2 * 384 * UNBATCHED   # double-and-add over a 256-bit scalar, generous: 768 ops
DP_MAX = 2 * S_max // 2 ** THETA_BITS + 2 * K
DP_COST = 2 ** 20                  # hash-table insert/lookup, transfer and bookkeeping per DP
REPLAY_OPS = 2 ** 12               # unbatched operations per live trail step, replay included (proof.md section 1.3)
START = 2 * SCALAR_MUL + 2 ** 14   # one start point [a]P + [b]Q from fresh coins

led = Ledger(C)
led.add("walk_steps", S_max * step_units)
led.add_instructions("adder_table", ADDERS * (2 * SCALAR_MUL + 2 ** 14), preprocessing=True)
led.add_instructions("initial_walk_starts", K * START, preprocessing=True)
# a new trail after each distinguished point (at most DP_MAX) and after each abandonment (at most K)
led.add_instructions("trail_restarts", (DP_MAX + K) * START)
led.add_instructions("distinguished_points", DP_MAX * DP_COST)
# one key match is resolved: both trails are replayed from their coins with coefficients
led.add_instructions("collision_replay", 2 * TRAIL_MAX * REPLAY_OPS * (UNBATCHED + 2 ** 10))
led.add_instructions("solve_verify_output", 2 * SCALAR_MUL + 2 ** 24)
led.add_instructions("input_validation", 2 * SCALAR_MUL + 2 ** 24)  # includes the [r]T = O check

