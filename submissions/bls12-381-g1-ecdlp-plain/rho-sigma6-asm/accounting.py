k_close = n_steps // C_ABANDON                         # k = floor(n / c)
assert Fraction(math.e) * n_steps * P_CLOSE / k_close <= Fraction(1, 2)
THETA = Fraction(1, 2 ** THETA_BITS)
# Pr[C_n >= k] <= (e n p_c / k)^k.  Fresh points >= n - 128k, each a DP with probability theta.
# A structural closure of length 65 or more traps the trail: rate below 2^-230 per step (Lemma C').
