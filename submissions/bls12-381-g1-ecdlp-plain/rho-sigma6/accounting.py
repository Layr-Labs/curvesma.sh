"""Exact accounting for the claim in proof.md (stdlib only; prints JSON).

All work is converted to target-group-operation equivalents: one batched incomplete
affine G1 addition (the 6M reference operation) is 1 unit; every other scalar AArch64
instruction is 1/C, C=2000. Integers and rationals are exact; logarithms are rounded
up to 6 decimals.
"""
import json
import math
from fractions import Fraction

from cscore.exact import Ledger, iroot_ceil, log2, log2_up

r = 0x73eda753299d7d483339d80809a1d80553bda402fffe5bfeffffffff00000001
C = 2000
ADDERS = 2 ** 16             # r-adding walk; index = bits 1..16 of the class key
K = 2 ** 30                  # walks (2^16 processors x 2^14-walk batches)
THETA_BITS = 60              # distinguished-point probability 2^-60
CAP = 64 * 2 ** THETA_BITS   # max steps between distinguished points before a walk is abandoned

# Classes: N nonzero order-6 classes, plus one for the identity (never reached by a walk).
N = (r - 1) // 6 + 1

# Success model (proof.md section 2): 1 - exp(-tau*(1-eps)) - delta with tau = T^2/(2N).
eps = Fraction(4, ADDERS) + 2 * Fraction(3, ADDERS) + 2 * Fraction(192, ADDERS ** 2)
delta = Fraction(1, 2 ** 20)
TAU_TARGET = Fraction(5303, 10000)
T_min = iroot_ceil(math.ceil(2 * N * TAU_TARGET), 2)
L = -(-T_min // K)                 # steps per walk counted towards the collision budget
T = K * L
S_max = K * (L + CAP)              # worst-case walk steps (each walk runs on to its next DP)

# Measured per-step instructions other than the six reference multiplications:
# 267.315 and 267.288 on two independent input sets (evidence/measurement/).
# 280 is charged; the margin also covers rare paths (proof.md section 3).
OTHER_PER_STEP = 280
step_units = 1 + Fraction(OTHER_PER_STEP, C)

# One unbatched step (affine add/double with its own inversion, adder selection and
# bookkeeping): measured 28,642.8 instructions on both input sets; 2^15 is charged.
UNBATCHED = 2 ** 15
SCALAR_MUL = 2 * 384 * UNBATCHED   # double-and-add over a 256-bit scalar, generous: 768 ops
DP_MAX = 2 * S_max // 2 ** THETA_BITS + 2 * K
DP_COST = 2 ** 20                  # hash-table insert/lookup, transfer and bookkeeping per DP

led = Ledger(C)
led.add("walk_steps", S_max * step_units)
led.add_instructions("adder_table", ADDERS * (2 * SCALAR_MUL + 2 ** 14), preprocessing=True)
led.add_instructions("walk_starts_and_restarts", 2 * K * (2 * SCALAR_MUL + 2 ** 14), preprocessing=True)
led.add_instructions("distinguished_points", DP_MAX * DP_COST)
led.add_instructions("collision_replay", 2 * (L + CAP) * (UNBATCHED + 2 ** 10))
led.add_instructions("solve_verify_output", 2 * SCALAR_MUL + 2 ** 24)
led.add_instructions("input_validation", 2 * SCALAR_MUL + 2 ** 24)  # includes the [r]T = O check

tau = Fraction(T * T, 2 * N)
p_model = 1 - math.exp(-float(tau * (1 - eps)))
p_claim = p_model - float(delta)
assert p_claim >= 0.39

peak_bytes = DP_MAX * 64 * 2 + K * 512 + ADDERS * 6 * 96 + 2 ** 24

out = led.report()
out.update({
    "L": str(L),
    "log2_L": log2(L),
    "log2_T": log2(T),
    "log2_S_max": log2(S_max),
    "step_units": str(step_units),
    "success": {"tau": float(tau), "eps": float(eps), "delta": float(delta),
                "model": p_model, "lower_bound": p_claim},
    "memory_bytes_log2": str(log2_up(peak_bytes)),
    "dp_max_log2": log2(DP_MAX),
})
print(json.dumps(out, indent=2))
