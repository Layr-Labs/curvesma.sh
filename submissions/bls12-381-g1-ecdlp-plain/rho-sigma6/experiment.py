"""Toy-curve test of the sigma walk (cscore.rho_sigma) on prime-order curves.

Input (JSON on stdin):
  curve: "j0" (y^2 = x^3 + b over p = 1 mod 3, order-6 classes, key = Montgomery y;
         b defaults to 4, the BLS12-381 G1 shape, walking in the prime-order subgroup
         of a small cofactor; b = 7 gives prime-order curves, the secp256k1 shape)
         or "a3" (y^2 = x^3 - 3x + b, negation classes, key = Montgomery x; P-256 shape)
  bits (of p), trials, adder_bits, dp_bits, walks, seed, b (j0 only)

Every trial samples a uniform secret, records all walk steps (round-robin,
including fruitless and escape steps) up to the first useful class collision, then
solves end to end through distinguished points and checks [x]P = Q.

Toy scale only: tests collision statistics, not production cost.
"""
import json
import random
import sys

from cscore import groups, rho_sigma


def main():
    cfg = json.load(sys.stdin)
    for k, v in rho_sigma.DEFAULTS.items():
        cfg.setdefault(k, v)
    cfg.setdefault("curve", "j0")
    rng = random.Random(cfg["seed"])
    if cfg["curve"] == "j0":
        cfg.setdefault("b", 4)
        if cfg["b"] == 7:
            E, G, n, beta, lam = groups.find_j0_curve(cfg["bits"], rng, b=7)
            h = 1
        else:
            E, G, n, beta, lam, h = groups.find_j0_subgroup_curve(cfg["bits"], rng, b=cfg["b"])
        cls = rho_sigma.Order6Y(E.p, n, beta, lam)
        curve = {"p": E.p, "a": 0, "b": E.b, "order": n, "cofactor": h, "beta": beta, "lambda": lam}
    elif cfg["curve"] == "a3":
        E, G, n = groups.find_prime_order_curve(cfg["bits"], rng)
        cls = rho_sigma.NegationX(E.p, n)
        curve = {"p": E.p, "a": E.a, "b": E.b, "order": n}
    else:
        raise SystemExit("curve must be j0 or a3")
    out = {"curve": curve, "config": cfg}
    out.update(rho_sigma.run(E, G, n, cls, cfg, rng))
    out["scope"] = "toy prime-order curves only; tests the walk's collision statistics, not production cost"
    print(json.dumps(out))


if __name__ == "__main__":
    main()
