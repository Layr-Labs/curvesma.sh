def cube_roots(E, n, G):
    """beta (mod p) and the matching lambda (mod n) with [lambda]G = (beta*x, y)."""
    p = E.p
    beta = next(pow(g, (p - 1) // 3, p) for g in range(2, p) if pow(g, (p - 1) // 3, p) != 1)
    lam = next(pow(g, (n - 1) // 3, n) for g in range(2, n) if pow(g, (n - 1) // 3, n) != 1)
    if E.mul(lam, G) != (beta * G[0] % p, G[1]):
        lam = lam * lam % n
    assert E.mul(lam, G) == (beta * G[0] % p, G[1])
    return beta, lam


def find_j0_curve(bits, rng, b=7):
    """Prime-order y^2 = x^3 + b over p = 1 mod 3 with n = 1 mod 3 (order-3 endomorphism).

    Returns (E, G, n, beta, lam). The rng call sequence matches the rho-order6
    experiment so seeds reproduce its curves.
    """
    while True:
        p = rng.randrange(1 << (bits - 1), 1 << bits) | 1
        if p % 3 != 1 or not is_prime(p):
            continue
        E = Curve(p, b)
        G = E.random_point(rng)
        # j=0 curve: the six twists have traces from 4p = t^2 + 3v^2.
        traces = set()
        for v in range(1, math.isqrt(4 * p // 3) + 1):
            t2 = 4 * p - 3 * v * v
            t = math.isqrt(t2)
            if t * t == t2:
                for tt in (t, (t + 3 * v) // 2, (t - 3 * v) // 2):
                    traces.add(tt)
                    traces.add(-tt)
                break
        orders = [p + 1 - t for t in traces if E.mul(p + 1 - t, G) is None]
        if len(orders) != 1:
            continue
        n = orders[0]
        if not is_prime(n) or n % 3 != 1 or n == p:
            continue
        beta, lam = cube_roots(E, n, G)
        E.n, E.G = n, G
        return E, G, n, beta, lam


def point_order_in_hasse(E, P):
    """All m in the Hasse interval with [m]P = O (baby-step/giant-step)."""
    p = E.p
    lo = p + 1 - 2 * math.isqrt(p) - 2
    width = 4 * math.isqrt(p) + 5
    s = math.isqrt(width) + 1
    baby = {}
    R = None
    for j in range(s):
        baby.setdefault(R, []).append(j)
        R = E.add(R, P)
    step = E.neg(E.mul(s, P))  # -[s]P
    gamma = E.mul(lo, P)       # [lo]P; want [lo + i*s + j]P = O  <=>  [j]P = -[lo + i*s]P
    out = []
    for i in range(width // s + 2):
        target = E.neg(gamma)
        for j in baby.get(target, []):
            m = lo + i * s + j
            if lo <= m < lo + width:
                out.append(m)
        gamma = E.add(gamma, E.neg(step))
    return sorted(set(out))


